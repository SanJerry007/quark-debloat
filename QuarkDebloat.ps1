# Real path of $p: the nearest existing ancestor is resolved by handle, the missing rest is appended.
function Get-AdRealPath([string]$p) {
    Initialize-AdNative
    $cur = Get-AdNormal $p; $rest = @()
    while ($true) {
        $open = if ($cur -match '^[A-Za-z]:$') { "$cur\" } else { $cur }
        if (Test-Path -LiteralPath $open) { break }
        $parent = [IO.Path]::GetDirectoryName($open)
        if (-not $parent -or $parent.TrimEnd('\') -eq $cur) { throw "no existing ancestor of $p" }
        $rest = @([IO.Path]::GetFileName($cur)) + $rest
        $cur = $parent.TrimEnd('\')
    }
    $real = ([AppDebloat.FinalPath]::Get($open)).TrimEnd('\')
    foreach ($r in $rest) { $real = "$real\$r" }
    $real
}
function Initialize-AdForbidden {
    $list = New-Object System.Collections.Generic.List[string]
    $sd = if ($env:SystemDrive) { $env:SystemDrive } else { 'C:' }
    foreach ($v in @($env:SystemRoot, "$env:SystemRoot\System32", "$env:SystemRoot\SysWOW64", $env:ProgramFiles,
                     ${env:ProgramFiles(x86)}, $env:ProgramW6432, $env:ProgramData, "$sd\Users", $env:USERPROFILE,
                     $env:PUBLIC, $env:APPDATA, $env:LOCALAPPDATA, "$env:LOCALAPPDATA\Programs", "$env:USERPROFILE\AppData",
                     "$env:USERPROFILE\AppData\LocalLow", "$env:USERPROFILE\Desktop", "$env:USERPROFILE\Documents",
                     $env:TEMP, "$env:CommonProgramFiles", "${env:CommonProgramFiles(x86)}")) {
        if ($v -and $v -notmatch '^\\?$') {
            try { $list.Add((Get-AdNormal $v)) } catch { }
            try { if (Test-Path -LiteralPath $v) { $list.Add((Get-AdRealPath $v)) } } catch { }
        }
    }
    $script:Ad.Forbidden = $list
}
function Get-AdBaseRefusal([string]$b) {
    if ([string]::IsNullOrWhiteSpace($b)) { return 'empty' }
    $n = Get-AdNormal $b
    if ($n -match '^[A-Za-z]:$' -or $n.StartsWith('\\')) { return 'drive root or UNC path' }
    foreach ($f in $script:Ad.Forbidden) {
        if ($n -ieq $f) { return "system location $f" }
        if ($f.StartsWith($n + '\', 'OrdinalIgnoreCase')) { return "ancestor of system location $f" }
    }
    if ((Test-Path -LiteralPath $n) -and ((Get-Item -LiteralPath $n -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) { return 'reparse point' }
    $null
}
# A base (install root or allowedRoots entry) is checked twice: as written and as its real path, so a junction
# anywhere above it cannot point the engine at a system location. Returns the real path.
function Add-AdBase([string]$lexical, [string]$label) {
    $why = Get-AdBaseRefusal $lexical
    if ($why) { throw "$label '$lexical' refused: $why" }
    try { $real = Get-AdRealPath $lexical } catch { throw "$label '$lexical' refused: cannot resolve its real path ($($_.Exception.Message))" }
    $why = Get-AdBaseRefusal $real
    if ($why) { throw "$label '$lexical' refused: its real path $real is a $why" }
    $script:Ad.Bases.Add($lexical); $script:Ad.RealBases[$lexical] = $real
    $real
}
# Returns $null when the path may be changed, else the reason it may not.
# -EditInPlace: the caller edits the file's content (ini-set, json-set, preboot-file-edit, a hook editing a settings
# file), which core.preserve files allow and core.files never do.
function Get-AdPathRefusal([string]$path, [switch]$AllowCoreAncestor, [switch]$NoTouch, [switch]$EditInPlace) {
    if ([string]::IsNullOrWhiteSpace($path)) { return 'empty path' }
    try { $full = Get-AdNormal $path } catch { return "invalid path '$path'" }
    if ($full -match '^[A-Za-z]:$' -or $full.StartsWith('\\')) { return "drive root or UNC path: $full" }
    foreach ($f in $script:Ad.Forbidden) { if ($full -ieq $f) { return "system location: $full" } }
    $base = $null
    foreach ($b in $script:Ad.Bases) {
        # An allowedRoots entry may itself be the target (e.g. a per-user staging folder to lock); the install root may not.
        if (Test-AdUnder $full $b -OrEqual:($b -ne $script:Ad.Root)) { $base = $b; break }
    }
    if (-not $base) { return "outside the install root and allowedRoots: $full" }
    $cur = $full
    while ($cur.Length -gt $base.Length) {
        if (Test-Path -LiteralPath $cur) {
            if ((Get-Item -LiteralPath $cur -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) { return "reparse point on the way: $cur" }
        }
        $cur = [IO.Path]::GetDirectoryName($cur)
    }
    # The lexical checks above cannot see a junction above the base; the real path can.
    try { $real = Get-AdRealPath $full } catch { return "cannot resolve the real path of ${full}: $($_.Exception.Message)" }
    $rb = $script:Ad.RealBases[$base]
    if (-not $rb) { return "no resolved real path for base $base" }
    if (-not (Test-AdUnder $real $rb -OrEqual:($base -ne $script:Ad.Root))) { return "real path $real leaves its root $rb" }
    foreach ($f in $script:Ad.Forbidden) { if ($real -ieq $f) { return "system location: $real" } }
    if ($NoTouch) { return $null }   # e.g. a firewall rule: the file itself is not changed
    foreach ($c in $script:Ad.CoreFiles) {
        if ($full -ieq $c) { return "core-function contract protects $c" }
        if (-not $AllowCoreAncestor -and $c.StartsWith($full + '\', 'OrdinalIgnoreCase')) { return "contains core file $c" }
    }
    foreach ($c in $script:Ad.PreserveFiles) {
        if ($full -ieq $c) { if (-not $EditInPlace) { return "core.preserve protects $c (only ini-set, json-set, preboot-file-edit or a hook may edit it in place)" } }
        elseif (-not $AllowCoreAncestor -and $c.StartsWith($full + '\', 'OrdinalIgnoreCase')) { return "contains preserved file $c" }
    }
    if ($script:Ad.OutOfProcessOnly -and $script:Ad.Root -and (Test-AdUnder $full $script:Ad.Root)) {
        return 'riskTier out-of-process-only forbids changes inside the install root'
    }
    $null
}
function Assert-AdPathSafe([string]$path, [switch]$AllowCoreAncestor, [switch]$NoTouch, [switch]$EditInPlace) {
    $r = Get-AdPathRefusal $path -AllowCoreAncestor:$AllowCoreAncestor -NoTouch:$NoTouch -EditInPlace:$EditInPlace
    if ($r) { throw "refused path: $r" }
}
# Stops processes by exact full path. A process of that name whose path cannot be read is an error, not a non-match.
function Stop-AdProcessByPath([string]$path) {
    $leaf = [IO.Path]::GetFileName($path)
    $l = $leaf.ToLowerInvariant()
    if ($script:Ad.CoreProcs -contains $l -and $script:Ad.Restartable -notcontains $l) { throw "refusing to stop core process $leaf (list it in core.restartable if the app relaunches it)" }
    $stem = [IO.Path]::GetFileNameWithoutExtension($leaf)
    $ids = @()
    foreach ($p in @(Get-Process -ErrorAction Stop | Where-Object { $_.ProcessName -ieq $stem })) {
        $pp = $null; try { $pp = $p.Path } catch { }
        if (-not $pp) { throw "cannot read the path of running $leaf (PID $($p.Id)); not stopping or replacing it blind" }
        if ($pp -ieq $path) { $ids += $p.Id }
    }
    foreach ($id in $ids) { Stop-Process -Id $id -Force -ErrorAction Stop }
    if ($ids) {
        Start-Sleep -Milliseconds 400
        $left = @(Get-Process -ErrorAction Stop | Where-Object { $ids -contains $_.Id })
        if ($left) { throw "$leaf (PID $($left[0].Id)) is still running after Stop-Process" }
    }
}
# Running processes whose image is exactly one of $paths: a list of 'name (PID n)'. A process of that name whose
# path cannot be read counts as running (unknown is never read as "not running").
function Get-AdRunningByPath([string[]]$paths) {
    Initialize-AdNative
    $out = @()
    foreach ($path in @($paths | Where-Object { $_ })) {
        $stem = [IO.Path]::GetFileNameWithoutExtension($path)
        foreach ($p in @(Get-Process -ErrorAction Stop | Where-Object { $_.ProcessName -ieq $stem })) {
            $pp = [AppDebloat.Modules]::ImagePath($p.Id)
            if (-not $pp) { $out += "$($p.ProcessName) (PID $($p.Id), path unreadable)" }
            elseif ($pp -ieq $path) { $out += "$($p.ProcessName) (PID $($p.Id))" }
        }
    }
    $out
}
# Kernel-side minimal processes: they hold no user-mode modules, so a refused snapshot of them hides nothing.
$script:AdMinimalProcs = @('System', 'Idle', 'Registry', 'Memory Compression', 'Secure System', 'vmmem', 'vmmemWSL')
# Isolated security processes (VBS trustlets, refused with error 998) and VM memory processes (vmmem*, refused with
# error 5): they run outside the normal user-mode loader and cannot load the app's DLLs.
$script:AdIsolatedProcs = @('LsaIso', 'NgcIso')
# Why an uninspectable process cannot hold the app's code, or $null. The image must be unknown or under System32,
# so an app process that merely borrows one of these names is never exempted.
function Get-AdExemptReason($p) {
    $sys = Get-AdNormal (Join-Path $env:SystemRoot 'System32')
    if ($p.Image -and -not (Test-AdUnder $p.Image $sys)) { return $null }
    if ($script:AdIsolatedProcs -contains $p.Name) { return 'isolated security process (VBS trustlet)' }
    if ($p.Name -like 'vmmem*') { return 'VM memory process' }
    if ($p.Err -eq 998 -and $p.Image) { return 'isolated process under System32 (error 998)' }
    $null
}
# Process-name patterns (from -IgnoreUninspectable and the manifest's checkLoadedExempt) that the loaded-module
# check skips when they cannot be inspected. A process that can be inspected is always checked.
function Test-AdIgnoredUninspectable($p) {
    if (-not $script:Ad) { return $null }
    foreach ($x in @($script:Ad.IgnoreUninspectable)) { if ($p.Name -like $x.Pattern) { return $x.Source } }
    $null
}
# True only when the process seen with start time $start is provably gone: no process has PID $id any more, it has
# exited, or the PID now belongs to a process that started at another time. Anything unreadable is no proof ($false).
function Test-AdProcessGone([int]$id, $start) {
    $q = $null
    try { $q = [Diagnostics.Process]::GetProcessById($id) } catch { return ($_.Exception.GetBaseException() -is [ArgumentException]) }
    try {
        $ex = $false; try { $ex = $q.HasExited } catch { }
        if ($ex) { return $true }
        if ($null -ne $start) { $now = $null; try { $now = $q.StartTime } catch { }; if ($null -ne $now -and $now -ne $start) { return $true } }
        $false
    } finally { $q.Dispose() }
}
# One record per running process: Name, Id, Session, Image, Modules (full paths, or $null when it could not be
# inspected), Err, Protected. Cached per run; -Fresh takes a new snapshot (used right before a folder is replaced).
# A snapshot refused with error 87 or 18 means the process exited meanwhile (scripts/list_modules.ps1), and 299 that
# survives the retries is also what an exited process still held open by another handle reports. Such a process is
# left out when Test-AdProcessGone proves it gone, and stays uninspectable while it still runs.
function Get-AdModuleMap([switch]$Fresh) {
    if (-not $Fresh -and $script:Ad -and $script:Ad.ModMap) { return $script:Ad.ModMap }
    Initialize-AdNative
    if (Test-AdIsAdmin) { try { [Diagnostics.Process]::EnterDebugMode() } catch { } }   # this process's own token only
    $map = New-Object System.Collections.Generic.List[object]
    foreach ($p in [Diagnostics.Process]::GetProcesses()) {
        try {
            $id = $p.Id; if ($id -le 4) { continue }
            $st = $null; try { $st = $p.StartTime } catch { }
            $err = 0; $mods = [AppDebloat.Modules]::List($id, [ref]$err)
            if ($null -eq $mods -and @(87, 18, 299) -contains $err -and (Test-AdProcessGone $id $st)) { continue }
            $sess = -1; try { $sess = $p.SessionId } catch { }
            $prot = if ($null -eq $mods) { [AppDebloat.Modules]::Protection($id) } else { 0 }
            $map.Add([pscustomobject]@{ Name = $p.ProcessName; Id = $id; Session = $sess; Image = [AppDebloat.Modules]::ImagePath($id); Modules = $mods; Err = $err; Protected = ($prot -eq 1) })
        } finally { $p.Dispose() }
    }
    if ($script:Ad) { $script:Ad.ModMap = $map }
    $map
}
# Which processes have a module loaded from under $dir, matched by full module path (case-insensitive prefix on the
# written and on the real path of $dir). Returns @{ Hits; Unknown }. A process that could not be inspected goes to
# Unknown (one that exited during the snapshot is not in the map at all, see Get-AdModuleMap), never to "not
# loaded", except kernel minimal processes and protected (PP/PPL) processes whose image lies
# outside the install root: those load only DLLs signed for their protection level, never the app's own files.
# Processes whose image is in $ExcludeImages are left out (they are stopped before the change). Exempt holds the
# isolated and VM processes that were skipped, Ignored the uninspectable ones skipped by -IgnoreUninspectable or
# checkLoadedExempt; Write-AdModuleExemptions prints both.
function Get-AdLoadedUnder([string]$dir, [string[]]$ExcludeImages = @(), [switch]$Fresh) {
    $pre = @((Get-AdNormal $dir)); try { $r = Get-AdRealPath $dir; if ($pre -notcontains $r) { $pre += $r } } catch { }
    $root = if ($script:Ad) { $script:Ad.Root } else { $null }
    $hits = New-Object System.Collections.Generic.List[string]; $unknown = New-Object System.Collections.Generic.List[string]
    $exempt = New-Object System.Collections.Generic.List[string]; $ignored = New-Object System.Collections.Generic.List[string]
    foreach ($p in (Get-AdModuleMap -Fresh:$Fresh)) {
        if ($p.Image -and @($ExcludeImages | Where-Object { $_ -ieq $p.Image }).Count) { continue }
        if ($null -eq $p.Modules) {
            if ($p.Session -eq 0 -and -not $p.Image -and $script:AdMinimalProcs -contains $p.Name) { continue }
            if ($p.Image -and $p.Protected -and -not ($root -and (Test-AdUnder $p.Image $root -OrEqual))) { continue }
            $why = Get-AdExemptReason $p
            if ($why) { $exempt.Add("$($p.Name) (PID $($p.Id), error $($p.Err): $why)"); continue }
            $src = Test-AdIgnoredUninspectable $p
            if ($src) { $ignored.Add("$($p.Name) (PID $($p.Id), error $($p.Err), by $src)"); continue }
            $unknown.Add("$($p.Name) (PID $($p.Id), error $($p.Err))"); continue
        }
        $short = $null
        foreach ($mp in [AppDebloat.Modules]::Under([string[]]$p.Modules, [string[]]$pre, [ref]$short)) { $hits.Add("$($p.Name) (PID $($p.Id)): $mp") }
        foreach ($mp in @($short)) {
            if (-not $mp) { continue }
            $real = $null; try { $real = Get-AdRealPath $mp } catch { }
            if ($real -and @($pre | Where-Object { Test-AdUnder $real $_ }).Count) { $hits.Add("$($p.Name) (PID $($p.Id)): $mp") }
        }
    }
    @{ Hits = $hits; Unknown = $unknown; Exempt = $exempt; Ignored = $ignored }
}
# Prints which uninspectable processes the module check skipped, once per distinct line per run.
function Write-AdModuleExemptions($lu) {
    foreach ($pair in @(@('exempted (cannot load app code)', $lu.Exempt), @('skipped by choice (uninspectable)', $lu.Ignored))) {
        if (-not @($pair[1]).Count) { continue }
        $line = "loaded-module check $($pair[0]): $(@($pair[1]) -join '; ')"
        if ($script:Ad.Shown.ContainsKey($line)) { continue }
        $script:Ad.Shown[$line] = 1; Say 'INFO' $line
    }
}
