# The object an item changes, named the way an action's target list names it: service name, \Folder\TaskName,
# file or folder path, exe name, HKLM\Key\Value (reg-set, reg-delete-value, shellext-block, toast-off), HKLM\Key
# (deleted keys), browser:id (browser-ext-block), program path (firewall), the hook's own item key.
# knownFailure.targets entries are matched against it.
function Get-AdItemSubject($it) {
    $d = $it.Data
    switch ($it.Prim) {
        'service' { return $d.name }
        'task' { return "$($d.path)$($d.name)" }
        'ifeo' { return $d.name }
        { @('regset', 'regval') -contains $_ } { return "$($d.hive)\$($d.sub)\$($d.name)" }
        'extblock' { return "$($d.browser):$($d.id)" }
        'regdel' { return "$($d.hive)\$($d.parent)\$($d.name)" }
        'firewall' { return $d.program }
        'hook' { return $it.Key.Substring($it.Key.IndexOf('|') + 1) }
        { @('file2dir', 'dir2file', 'acl', 'iniset', 'jsonset') -contains $_ } { return $d.path }
    }
    $null
}
# Registry names are compared in one spelling, the hive as HKLM\ or HKCU\ and no trailing backslash, so a targets
# entry may copy any spelling Split-AdRegPath accepts (HKEY_CURRENT_USER\, HKCU:\, a trailing \). Others pass as is.
function ConvertTo-AdKnownName([string]$s) {
    if ($s -notmatch '^(?i)(HKEY_LOCAL_MACHINE|HKLM:?|HKEY_CURRENT_USER|HKCU:?)\\') { return $s }
    ($s -replace '^(?i)(HKEY_LOCAL_MACHINE|HKLM:?)\\', 'HKLM\' -replace '^(?i)(HKEY_CURRENT_USER|HKCU:?)\\', 'HKCU\').TrimEnd('\')
}
# The knownFailure that covers this item, or $null. Without targets it covers every item of the action; with
# targets only the items whose subject equals one of them, or matches it when it has wildcards (tokens expanded).
function Get-AdKnownFailure($it) {
    $kf = $script:Ad.KnownFailures[$it.ActionId]
    if (-not $kf) { return $null }
    if (-not $script:Ad.KnownTargets.ContainsKey($it.ActionId)) { return $kf }
    $s = ConvertTo-AdKnownName (Get-AdItemSubject $it)
    if (-not $s) { return $null }
    foreach ($p in @($script:Ad.KnownTargets[$it.ActionId])) {
        if ($p -match '[\*\?]') { if ($s -like $p.Replace('[', '`[').Replace(']', '`]')) { return $kf } }
        elseif ($s -ieq $p) { return $kf }
    }
    $null
}
function Add-AdKnownFailed([string]$id, $kf) {
    $script:Ad.KnownFailed++
    if (-not $script:Ad.KnownBy.Contains($id)) { $script:Ad.KnownBy[$id] = @{ N = 0; Ref = "$(AdGet $kf 'ref')" } }
    $script:Ad.KnownBy[$id].N++
}
# A failed item: a known failure is a WARN counted apart (no diagnostics), anything else a FAIL with diagnostics.
function Write-AdItemFailure($it, $er) {
    $msg = $er.Exception.Message
    if ($it.Known) {
        Add-AdKnownFailed $it.ActionId $it.Known
        Say 'WARN' "[$($it.ActionId)] known failure (ref $(AdGet $it.Known 'ref')): $(AdGet $it.Known 'reason') :: $($it.Desc) :: $msg" -NoCount
    } else {
        Say 'FAIL' "$($it.Desc) :: $msg"
        if (Test-AdAccessDenied $er) { Write-AdDenialDiagnostics $it }
    }
}
function Get-AdRegSetItem($a, [string]$hive, $view, [string]$sub, [string]$name, $value, [string]$kind, [string]$desc) {
    $cur = Get-AdRegValue $hive $view $sub $name
    # The kind counts too: the String '030000' is not the Binary 03 00 00.
    if ($cur.exists -and $cur.kind -eq $kind -and (Test-AdSame $cur.value $value)) { Say 'SKIP' "$desc (already set)"; return }
    if ($cur.kind -eq 'Unknown') { throw "$hive\$sub $name holds data of a kind that cannot be journaled, so it could not be restored; not changed" }
    New-AdItem $a 'regset' "reg:$hive$view\$sub|$name" $desc @{ hive = $hive; view = "$view"; sub = $sub; name = $name; value = $value; kind = $kind } $cur ([ordered]@{ exists = $true; value = $value; kind = $kind })
}
function Get-AdRegDelItem($a, [string]$hive, $view, [string]$parent, [string]$name) {
    $sub = "$parent\$name"
    $why = Get-AdRegKeyRefusal $sub; if ($why) { throw $why }
    if (-not (Test-AdRegKey $hive $view $sub)) { return }
    New-AdItem $a 'regdel' "regkey:$hive$view\$sub" "Delete registry key $hive\$sub$(if ("$view" -eq '32' -and $hive -eq 'HKLM') { ' (32-bit view)' })" @{ hive = $hive; view = "$view"; parent = $parent; name = $name } @{ export = $null } ([ordered]@{ keyExists = $false })
}
function Get-AdTargets($a) {
    $t = @(AdGet $a 'target' @())
    foreach ($x in $t) { Resolve-AdTargets $x }
}
# True when a current target of the action names $path: equal to it, or matching it when the target has wildcards.
function Test-AdTargetNames($a, [string]$path) {
    foreach ($t in @(AdGet $a 'target' @())) {
        $x = Expand-AdPath $t
        if ($x -match '[\*\?]') { if ($path -like $x.Replace('[', '`[').Replace(']', '`]')) { return $true } }
        elseif ($path -ieq $x) { return $true }
    }
    $false
}
# Placeholders this action placed earlier (active journal entries) that are gone now, deleted by a cleaner, an updater
# or the user. A glob target resolves only against items that exist, so the journal finds them, not the target list.
# Each is planned again under its own key, its kind taken from the entry's after-state (the journal keeps its first
# original, and an identical after-state adds no line), while its parent folder exists and a current target still
# names it; otherwise a SKIP line says why. $planned holds the keys the target list already planned.
function Get-AdPlaceholderRedo($a, [string[]]$planned) {
    $id = AdGet $a 'id'; $bk = [bool](AdGet $a 'backup' $true); $chk = [bool](AdGet $a 'checkLoaded' $true)
    foreach ($e in @($script:Ad.Journal.Values)) {
        if ((AdGet $e 'actionId') -ne $id -or @('file2dir', 'dir2file') -notcontains (AdGet $e 'prim')) { continue }
        $p = [string](AdGet (AdGet $e 'data') 'path'); $key = "fs:$p"
        if (-not $p -or @($planned) -contains $key -or (Test-Path -LiteralPath $p)) { continue }
        $kind = AdGet (AdGet $e 'after') 'kind'
        if (@('emptyDir', 'placeholderFile') -notcontains $kind) { continue }
        if (-not (Test-AdTargetNames $a $p)) { Say 'SKIP' "${p}: the placeholder is gone, but no current target of $id names it; not re-created"; continue }
        # Set-AdPlaceholder creates missing parents, so it would rebuild a version folder the vendor removed.
        $parent = [IO.Path]::GetDirectoryName($p)
        if (-not $parent -or -not (Test-Path -LiteralPath $parent -PathType Container)) { Say 'SKIP' "${p}: parent gone (version moved?)"; continue }
        $why = Get-AdPathRefusal $p
        if ($why) { Say 'WARN' "${p}: the placeholder is gone and is not re-created: $why"; continue }
        if ($kind -eq 'emptyDir') {
            New-AdItem $a 'file2dir' $key "Re-create placeholder directory (deleted since it was placed): $p" @{ path = $p; backup = $bk; stopHosts = @() } @{ existed = $false } ([ordered]@{ kind = 'emptyDir' })
        } else {
            $hosts = @(@(AdGet $a 'stopHosts' @()) | ForEach-Object { Get-AdNormal (Expand-AdPath $_) })
            New-AdItem $a 'dir2file' $key "Re-create read-only placeholder file (deleted since it was placed): $p" @{ path = $p; backup = $bk; checkLoaded = $chk; stopHosts = $hosts } @{ existed = $false } ([ordered]@{ kind = 'placeholderFile' })
        }
    }
}
function Get-AdPrebootIdentity([string]$scr) { "powershell.exe|-NoProfile -ExecutionPolicy Bypass -File `"$scr`"|" }
