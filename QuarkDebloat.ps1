    // Surgical JSON edits: locate the value a JSON pointer names and replace, insert or remove only that span, so
    // the rest of the file stays byte for byte as the vendor wrote it.
    public class JsonLoc {
        public bool Found; public int ValStart = -1, ValEnd = -1, MemberStart = -1;
        public int Depth;              // segments resolved
        public int ParentOpen = -1;    // index of the '{' of the deepest resolved object when not found
        public bool ParentIsObject;
    }
    public static class JsonPtr {
        static int Ws(string s, int i) { while (i < s.Length && (s[i] == ' ' || s[i] == '\t' || s[i] == '\r' || s[i] == '\n')) i++; return i; }
        static void Expect(string s, int i, char c) { if (i >= s.Length || s[i] != c) throw new FormatException("JSON: expected '" + c + "' at offset " + i); }
        static int SkipString(string s, int i) {
            Expect(s, i, '"'); i++;
            while (i < s.Length) { char c = s[i]; if (c == '\\') { i += 2; continue; } if (c == '"') return i + 1; i++; }
            throw new FormatException("JSON: unterminated string");
        }
        static string ReadString(string s, int i, out int end) {
            end = SkipString(s, i); StringBuilder sb = new StringBuilder();
            for (int j = i + 1; j < end - 1; j++) {
                char c = s[j];
                if (c != '\\') { sb.Append(c); continue; }
                char n = s[++j];
                switch (n) {
                    case 'b': sb.Append('\b'); break; case 'f': sb.Append('\f'); break; case 'n': sb.Append('\n'); break;
                    case 'r': sb.Append('\r'); break; case 't': sb.Append('\t'); break;
                    case 'u': sb.Append((char)Convert.ToInt32(s.Substring(j + 1, 4), 16)); j += 4; break;
                    default: sb.Append(n); break;
                }
            }
            return sb.ToString();
        }
        static int SkipValue(string s, int i) {
            i = Ws(s, i); if (i >= s.Length) throw new FormatException("JSON: value expected at end of text");
            char c = s[i];
            if (c == '"') return SkipString(s, i);
            if (c == '{' || c == '[') {
                char close = c == '{' ? '}' : ']'; i = Ws(s, i + 1);
                if (i < s.Length && s[i] == close) return i + 1;
                while (true) {
                    if (c == '{') { i = Ws(s, i); i = SkipString(s, i); i = Ws(s, i); Expect(s, i, ':'); i++; }
                    i = Ws(s, SkipValue(s, i));
                    if (i < s.Length && s[i] == ',') { i++; continue; }
                    Expect(s, i, close); return i + 1;
                }
            }
            int k = i; while (k < s.Length && ",}] \t\r\n".IndexOf(s[k]) < 0) k++;
            if (k == i) throw new FormatException("JSON: bad value at offset " + i);
            return k;
        }
        public static JsonLoc Find(string s, string[] segs) {
            JsonLoc r = new JsonLoc(); int vs = Ws(s, 0), ms = -1;
            for (int d = 0; d < segs.Length; d++) {
                int i = Ws(s, vs);
                if (i >= s.Length) throw new FormatException("JSON: empty document");
                if (s[i] == '{') {
                    int open = i, hitV = -1, hitM = -1; i = Ws(s, i + 1);
                    if (s[i] != '}') {
                        while (true) {
                            i = Ws(s, i); int ks = i, ke; string key = ReadString(s, i, out ke);
                            i = Ws(s, ke); Expect(s, i, ':'); int v = Ws(s, i + 1); int ve = SkipValue(s, v);
                            if (key == segs[d]) { hitV = v; hitM = ks; }       // the last duplicate wins, as in most parsers
                            i = Ws(s, ve); if (s[i] == ',') { i++; continue; } Expect(s, i, '}'); break;
                        }
                    }
                    if (hitV < 0) { r.Depth = d; r.ParentOpen = open; r.ParentIsObject = true; return r; }
                    vs = hitV; ms = hitM;
                } else if (s[i] == '[') {
                    int idx; if (!int.TryParse(segs[d], out idx) || idx < 0) { r.Depth = d; return r; }
                    i = Ws(s, i + 1); int n = 0, hit = -1;
                    if (s[i] != ']') {
                        while (true) {
                            int v = Ws(s, i); int ve = SkipValue(s, v);
                            if (n == idx) hit = v; n++;
                            i = Ws(s, ve); if (s[i] == ',') { i++; continue; } Expect(s, i, ']'); break;
                        }
                    }
                    if (hit < 0) { r.Depth = d; return r; }
                    vs = hit; ms = -1;
                } else { r.Depth = d; return r; }
            }
            r.Found = true; r.Depth = segs.Length; r.ValStart = vs; r.ValEnd = SkipValue(s, vs); r.MemberStart = ms;
            return r;
        }
        public static string Quote(string v) {
            StringBuilder sb = new StringBuilder("\"");
            foreach (char c in v) {
                if (c == '"') sb.Append("\\\""); else if (c == '\\') sb.Append("\\\\");
                else if (c < 0x20) sb.Append("\\u" + ((int)c).ToString("x4")); else sb.Append(c);
            }
            return sb.Append('"').ToString();
        }
        // Canonical text of one JSON value: no whitespace outside strings, strings re-quoted with minimal escapes.
        public static string Canon(string s) {
            StringBuilder sb = new StringBuilder(); int i = 0;
            while (i < s.Length) {
                char c = s[i];
                if (c == ' ' || c == '\t' || c == '\r' || c == '\n') { i++; continue; }
                if (c == '"') { int e; sb.Append(Quote(ReadString(s, i, out e))); i = e; continue; }
                sb.Append(c); i++;
            }
            return sb.ToString();
        }
        // Span [start, end) to cut so that the member at memberStart..valEnd disappears with one adjacent comma: the
        // exact inverse of an insert of "key":value, right after '{'.
        public static int[] MemberCut(string s, int memberStart, int valEnd) {
            int j = Ws(s, valEnd);
            if (j < s.Length && s[j] == ',') return new int[] { memberStart, j + 1 };
            int k = memberStart - 1; while (k >= 0 && (s[k] == ' ' || s[k] == '\t' || s[k] == '\r' || s[k] == '\n')) k--;
            if (k >= 0 && s[k] == ',') return new int[] { k, valEnd };
            return new int[] { memberStart, valEnd };
        }
        public static bool IsEmptyObject(string s, int open) { int j = Ws(s, open + 1); return j < s.Length && s[j] == '}'; }
    }
}
