# Quark hooks. No vendor secrets: the hook only flips one boolean user preference that the app's own settings page
# also writes (browser.quark.floating_ball.settings).
# The other actions (staged installer, clipboard watcher, native host keys, shell verbs and their options) use the
# engine's own types (acl-deny-write, json-set, reg-delete-key, placeholders) and need no hook.

# Returns @{ start; end; value } for a top-level key of the JSON object that starts at $objStart ('{'), or $null.
# Scans with string/escape awareness so keys inside nested objects or string values are never matched.
function Find-QkJsonBool([string]$t, [int]$objStart, [string]$key) {
    $depth = 0; $inStr = $false; $esc = $false; $strStart = -1
    for ($i = $objStart; $i -lt $t.Length; $i++) {
        $c = $t[$i]
        if ($inStr) {
            if ($esc) { $esc = $false; continue }
            if ($c -eq '\') { $esc = $true; continue }
            if ($c -eq '"') {
                $inStr = $false
                if ($depth -eq 1 -and $t.Substring($strStart, $i - $strStart + 1) -eq "`"$key`"") {
                    $j = $i + 1; while ($j -lt $t.Length -and $t[$j] -match '\s') { $j++ }
                    if ($j -lt $t.Length -and $t[$j] -eq ':') {
                        $j++; while ($j -lt $t.Length -and $t[$j] -match '\s') { $j++ }
                        foreach ($lit in 'true', 'false') {
                            if ($t.Length -ge $j + $lit.Length -and $t.Substring($j, $lit.Length) -eq $lit) { return @{ start = $j; end = $j + $lit.Length; value = ($lit -eq 'true') } }
                        }
                        return $null
                    }
                }
            }
            continue
        }
        if ($c -eq '"') { $inStr = $true; $strStart = $i; continue }
        if ($c -eq '{' -or $c -eq '[') { $depth++; continue }
        if ($c -eq '}' -or $c -eq ']') { $depth--; if ($depth -eq 0) { return $null }; continue }
    }
    $null
}
