# ------------------------------------------------------------------ ACL (exact deny entries only)
$script:AdDenyWriteRights = [int]([Security.AccessControl.FileSystemRights]'WriteData, AppendData, WriteExtendedAttributes, WriteAttributes')
function Get-AdDenyRights([string]$path, [string]$sid, [int]$inheritance) {
    $sec = (Get-Item -LiteralPath $path -Force).GetAccessControl('Access')
    $sum = 0
    foreach ($r in $sec.GetAccessRules($true, $false, [Security.Principal.SecurityIdentifier])) {
        if ("$($r.AccessControlType)" -eq 'Deny' -and $r.IdentityReference.Value -eq $sid -and [int]$r.InheritanceFlags -eq $inheritance -and [int]$r.PropagationFlags -eq 0) {
            $sum = $sum -bor [int]$r.FileSystemRights
        }
    }
    $sum
}
# Adds, or with -Remove takes away, exactly $rights from the explicit deny entry of $sid with these inheritance flags.
# Other entries, and other rights in the same entry, are left as they are.
function Set-AdDenyAce([string]$path, [string]$sid, [int]$rights, [int]$inheritance, [switch]$Remove) {
    $item = Get-Item -LiteralPath $path -Force
    $sec = $item.GetAccessControl('Access')
    $id = New-Object Security.Principal.SecurityIdentifier $sid
    $mk = { param($r) New-Object Security.AccessControl.FileSystemAccessRule($id, [Security.AccessControl.FileSystemRights]$r,
                [Security.AccessControl.InheritanceFlags]$inheritance, [Security.AccessControl.PropagationFlags]::None, [Security.AccessControl.AccessControlType]::Deny) }
    if ($Remove) {
        foreach ($r in @($sec.GetAccessRules($true, $false, [Security.Principal.SecurityIdentifier]))) {
            if ("$($r.AccessControlType)" -ne 'Deny' -or $r.IdentityReference.Value -ne $sid -or [int]$r.InheritanceFlags -ne $inheritance -or [int]$r.PropagationFlags -ne 0) { continue }
            if (-not ([int]$r.FileSystemRights -band $rights)) { continue }
            [void]$sec.RemoveAccessRuleSpecific($r)
            $restRights = [int]$r.FileSystemRights -band (-bnot $rights)
            if ($restRights) { $sec.AddAccessRule((& $mk $restRights)) }
        }
    } else { $sec.AddAccessRule((& $mk $rights)) }
    $item.SetAccessControl($sec)
}
# rights "write+protect" also denies these, so the denied user can neither delete the folder's content (a placeholder
# included) nor strip the entry or take ownership.
$script:AdDenyProtectRights = [int]([Security.AccessControl.FileSystemRights]'Delete, DeleteSubdirectoriesAndFiles, ChangePermissions, TakeOwnership')
# Why "write+protect" may not be used on $path for $sid, or $null. The owner of an object keeps an implicit WRITE_DAC
# that no deny entry takes away, and only an enabled SID counts as owner. An Administrators owner therefore lets the
# elevated tool (Administrators enabled) lift and undo exactly its own rights, while the user's filtered token
# (Administrators deny-only) cannot. An owner that is the denied SID could strip the entry; a SYSTEM, TrustedInstaller
# or other owner would lock the elevated tool out of its own entry, since the deny binds the user SID it carries.
function Get-AdProtectRefusal([string]$path, [string]$sid) {
    $own = $null; try { $own = (Get-Item -LiteralPath $path -Force).GetAccessControl('Owner').GetOwner([Security.Principal.SecurityIdentifier]).Value } catch { }
    if (-not $own) { return "rights write+protect on ${path}: its owner cannot be read" }
    if ($own -eq $sid) { return "rights write+protect on ${path}: its owner is the denied SID $sid, which keeps WRITE_DAC and could strip the entry; use rights write" }
    if ($own -ne 'S-1-5-32-544') { return "rights write+protect on ${path}: its owner is $own; only an Administrators (S-1-5-32-544) owner keeps the entry out of the user's reach while the elevated tool can still lift and undo it; use rights write" }
    $null
}
# Every right the tool added for one acl journal entry: the first line's addedRights plus the latest after.rights
# (a later line, written when the tool re-adds rights or a rebuilt manifest asks for more, carries the full set).
function Get-AdAclAdded($e) { [int](AdGet (AdGet $e 'original') 'addedRights' 0) -bor [int](AdGet (AdGet $e 'after') 'rights' 0) }
# Deny entries this tool put on a parent or ancestor folder of $path (active acl: journal entries) bind the elevated
# token too, which carries the same user SID, so the engine could not create or remove its own placeholder inside such
# a folder. Enter-AdAclLift takes away exactly the journaled rights that are present (after a note journal line that
# names them) and returns what it took; Exit-AdAclLift, called from a finally block, puts the same rights back.
function Enter-AdAclLift([string]$path, [string]$actionId, [string]$key) {
    $full = Get-AdNormal $path; $lifts = @()
    foreach ($je in @($script:Ad.Journal.Values)) {
        if ((AdGet $je 'prim') -ne 'acl') { continue }
        $jd = AdGet $je 'data'; $ap = [string](AdGet $jd 'path')
        if (-not $ap -or -not (Test-AdUnder $full (Get-AdNormal $ap)) -or -not (Test-Path -LiteralPath $ap -PathType Container)) { continue }
        $sid = [string](AdGet $jd 'sid'); $inh = [int](AdGet $jd 'inheritance' 0)
        $have = (Get-AdDenyRights $ap $sid $inh) -band (Get-AdAclAdded $je)
        if ($have) { $lifts += [pscustomobject]@{ Path = $ap; Sid = $sid; Inh = $inh; Rights = $have } }
    }
    if (-not $lifts.Count) { return @() }
    $names = @($lifts | ForEach-Object { "acl:$($_.Path)|$($_.Sid) rights $($_.Rights)" })
    Add-AdJournalLine ([ordered]@{ kind = 'note'; ts = (Get-Date -Format s); app = $script:Ad.AppId; actionId = $actionId; key = $key
                                   note = 'own deny entries lifted for the moment to create or remove this placeholder, then put back'; lifted = $names })
    Say 'INFO' "lifting own deny entr$(if ($lifts.Count -gt 1) { 'ies' } else { 'y' }) for the moment to change ${path}: $($names -join '; ')"
    $done = @()
    try { foreach ($l in $lifts) { Set-AdDenyAce $l.Path $l.Sid $l.Rights $l.Inh -Remove; $done += $l } }
    catch { Exit-AdAclLift $done; throw }
    , $done
}
function Exit-AdAclLift($lifts) {
    $bad = @()
    foreach ($l in @($lifts)) {
        if ($null -eq $l) { continue }
        try { Set-AdDenyAce $l.Path $l.Sid $l.Rights $l.Inh } catch { $bad += "$($l.Path) for $($l.Sid): $($_.Exception.Message)" }
    }
    if ($bad.Count) { throw "could not put back own deny entr$(if ($bad.Count -gt 1) { 'ies' } else { 'y' }) ($($bad -join '; ')); the acl-deny-write action re-adds them on its next run" }
}

# ------------------------------------------------------------------ registry
function Open-AdHive([string]$hive, $view = 64) {
    $h = switch ($hive) { 'HKLM' { [Microsoft.Win32.RegistryHive]::LocalMachine } 'HKCU' { [Microsoft.Win32.RegistryHive]::CurrentUser } default { throw "unsupported hive '$hive'" } }
    $v = if ("$view" -eq '32') { [Microsoft.Win32.RegistryView]::Registry32 } else { [Microsoft.Win32.RegistryView]::Registry64 }
    [Microsoft.Win32.RegistryKey]::OpenBaseKey($h, $v)
}
function Split-AdRegPath([string]$p) {
    if ($p -match '^(HKLM|HKEY_LOCAL_MACHINE|HKLM:)\\(.+)$') { return @('HKLM', $Matches[2].TrimEnd('\')) }
    if ($p -match '^(HKCU|HKEY_CURRENT_USER|HKCU:)\\(.+)$') { return @('HKCU', $Matches[2].TrimEnd('\')) }
    throw "registry path must start with HKLM\ or HKCU\: $p"
}
# Binary (and None) data travels as a lowercase hex string: in the manifest, the journal and every comparison.
# ConvertTo-AdHex accepts '03 00 00 00', '03,00', '03-00' or 'hex:0300' and throws on anything that is not whole bytes.
function ConvertTo-AdHex($v) {
    # A journal from engine 1.5 or older holds the bytes as numbers; AdGet hands a one-byte array back as a bare number.
    if (($v -is [array] -and $v -isnot [byte[]]) -or $v -is [int] -or $v -is [long]) { $v = [byte[]]@($v) }
    if ($v -is [byte[]]) { return ([BitConverter]::ToString($v) -replace '-', '').ToLowerInvariant() }
    $s = ("$v" -replace '^(?i)hex:', '' -replace '[\s,\-]', '').ToLowerInvariant()
    if ($s -notmatch '^([0-9a-f]{2})*$') { throw "not a hex byte string: '$v'" }
    $s
}
function ConvertFrom-AdHex($v) {
    $s = ConvertTo-AdHex $v; $b = New-Object byte[] ($s.Length / 2)
    for ($i = 0; $i -lt $b.Length; $i++) { $b[$i] = [Convert]::ToByte($s.Substring(2 * $i, 2), 16) }
    , $b
}
function Get-AdRegValue([string]$hive, $view, [string]$sub, [string]$name) {
    $b = Open-AdHive $hive $view; $k = $b.OpenSubKey($sub)
    $r = @{ keyExisted = [bool]$k; exists = $false; value = $null; kind = $null }
    if ($k) {
        if ($k.GetValueNames() -contains $name) {
            $r.exists = $true
            $r.kind = "$($k.GetValueKind($name))"
            $r.value = $k.GetValue($name, $null, [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)
            if ($r.value -is [byte[]]) { $r.value = ConvertTo-AdHex $r.value }
        }
        $k.Close()
    }
    $b.Close(); $r
}
function Set-AdRegValue([string]$hive, $view, [string]$sub, [string]$name, $value, [string]$kind) {
    $b = Open-AdHive $hive $view; $k = $b.CreateSubKey($sub)
    try {
        $rk = [Microsoft.Win32.RegistryValueKind]$kind
        if ($kind -eq 'Binary' -or $kind -eq 'None') { $v = ConvertFrom-AdHex $value }
        else { $v = switch ($kind) { 'DWord' { [int]$value } 'QWord' { [long]$value } 'MultiString' { [string[]]@($value) } default { [string]$value } } }
        $k.SetValue($name, $v, $rk)
    } finally { $k.Close(); $b.Close() }
}
# Registry data as a summary for plan, journal and undo messages: its kind and size, never the text or bytes (a Run
# value's command line can carry a token); only a DWord or QWord number is printed. The data itself stays in 'original'.
function Format-AdRegData($kind, $value) {
    switch ("$kind") {
        { @('DWord', 'QWord') -contains $_ } { return "$kind $value" }
        'MultiString' { return "MultiString, $(@($value | Where-Object { $null -ne $_ }).Count) string(s)" }
        { @('Binary', 'None') -contains $_ } { return "$kind, $(if ($value -is [string]) { [int]($value.Length / 2) } else { @($value | Where-Object { $null -ne $_ }).Count }) byte(s)" }
    }
    "$kind, $("$value".Length) chars"
}
function Test-AdRegKey([string]$hive, $view, [string]$sub) {
    $b = Open-AdHive $hive $view; $k = $b.OpenSubKey($sub); $ok = [bool]$k; if ($k) { $k.Close() }; $b.Close(); $ok
}
function Get-AdRegSubKeys([string]$hive, $view, [string]$sub) {
    $b = Open-AdHive $hive $view; $k = $b.OpenSubKey($sub); $n = @()
    if ($k) { $n = @($k.GetSubKeyNames()); $k.Close() }
    $b.Close(); $n
}
$script:AdRegShallow = @('software', 'software\classes', 'software\classes\clsid', 'software\classes\wow6432node',
    'software\classes\wow6432node\clsid', 'software\microsoft', 'software\wow6432node', 'system', 'system\currentcontrolset',
    'system\currentcontrolset\services', 'software\microsoft\windows\currentversion', 'software\microsoft\windows\currentversion\run')
function Get-AdRegKeyRefusal([string]$sub) {
    $s = $sub.Trim('\').ToLowerInvariant()
    if (($s -split '\\').Count -lt 3) { return "registry key too shallow: $sub" }
    if ($script:AdRegShallow -contains $s) { return "registry key is a shared root: $sub" }
    if ($s -like 'system\currentcontrolset\services\*') { return 'use service-disable for services, never delete them' }
    $null
}
# Every existing key that $sub names: a segment may hold * and ? (matched against the subkey names one level down).
function Resolve-AdRegKeys([string]$hive, $view, [string]$sub) {
    $cur = @('')
    foreach ($seg in $sub.Trim('\').Split('\')) {
        $next = @()
        foreach ($c in $cur) {
            if ($seg -match '[\*\?]') {
                $p = $seg.Replace('[', '`[').Replace(']', '`]')
                foreach ($n in (Get-AdRegSubKeys $hive $view $c)) { if ($n -like $p) { $next += $(if ($c) { "$c\$n" } else { $n }) } }
            } else { $next += $(if ($c) { "$c\$seg" } else { $seg }) }
        }
        $cur = $next; if (-not $cur.Count) { return }
    }
    foreach ($c in $cur) { if (Test-AdRegKey $hive $view $c) { $c } }
}
