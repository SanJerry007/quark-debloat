    "$s; last elevated enumeration ($($saved.When.ToString('yyyy-MM-dd HH:mm'))): $($hit.Count) match$(if ($hit.Count -ne 1) { 'es' })" +
        $(if ($hit.Count) { " ($((@($hit | ForEach-Object { "$($_.Path)$($_.Name)" }) | Select-Object -First 5) -join ', '))" } else { '' })
}
