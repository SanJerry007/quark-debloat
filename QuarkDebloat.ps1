# Deletes $leaf and then each parent up to and including $top, while the key is empty; stops at the first key that
# holds anything. Used only for keys the journal shows the tool created.
function Remove-AdEmptyRegKeys([string]$hive, $view, [string]$leaf, [string]$top) {
    if (-not $top -or -not ($leaf -ieq $top -or $leaf.StartsWith("$top\", 'OrdinalIgnoreCase'))) { return }
    $cur = $leaf
    while ($true) {
        $b = Open-AdHive $hive $view
        try {
            $k = $b.OpenSubKey($cur)
            if ($k) { $empty = ($k.ValueCount -eq 0 -and $k.SubKeyCount -eq 0); $k.Close(); if (-not $empty) { return }; $b.DeleteSubKey($cur, $false) }
        } finally { $b.Close() }
        if ($cur -ieq $top) { return }
        $cur = $cur.Substring(0, $cur.LastIndexOf('\'))
    }
}

# ------------------------------------------------------------------ INI editor (self-contained: copied into pre-logon tasks)
# $Triples: array of @(section, key, value); value $null removes the key. Returns @{ Diff; Original } where
# Original holds triples with the values found before the edit ($null = was absent). Writes only when $Write.
# A BOM decides the encoding; without one, $Encoding (utf-8, utf-16le, or a code page name or number such as gbk
# or 936) is used, else byte-preserving Latin-1 (safe for ASCII keys and values in any single-byte or UTF-8 file).
# $DropEmpty: sections whose header is removed when no key is left in them (undo of a section the tool created).
function Update-AdIni([string]$Path, $Triples, [bool]$Write, [string]$Encoding = '', [string[]]$DropEmpty = @()) {
    $raw = [IO.File]::ReadAllBytes($Path); $skip = 0
    if ($raw.Length -ge 2 -and $raw[0] -eq 0xFF -and $raw[1] -eq 0xFE) { $enc = [Text.Encoding]::Unicode; $skip = 2 }
    elseif ($raw.Length -ge 3 -and $raw[0] -eq 0xEF -and $raw[1] -eq 0xBB -and $raw[2] -eq 0xBF) { $enc = New-Object Text.UTF8Encoding $false; $skip = 3 }
    elseif ($Encoding -and $Encoding -ne 'auto') {
        $enc = switch ($Encoding) { 'utf-8' { New-Object Text.UTF8Encoding $false, $true } 'utf-16le' { [Text.Encoding]::Unicode }
                                    default { $cp = 0; if ([int]::TryParse($Encoding, [ref]$cp)) { [Text.Encoding]::GetEncoding($cp) } else { [Text.Encoding]::GetEncoding($Encoding) } } }
    }
    else { $enc = [Text.Encoding]::GetEncoding(28591) }
    $text = $enc.GetString($raw, $skip, $raw.Length - $skip)
    $nl = if ($text -match "`r`n") { "`r`n" } else { "`n" }
    $want = @{}; $order = New-Object System.Collections.Generic.List[string]
    foreach ($t in @($Triples)) {
        $sec = [string]$t[0]; if (-not $want.ContainsKey($sec)) { $want[$sec] = [ordered]@{}; $order.Add($sec) }
        $want[$sec][[string]$t[1]] = $t[2]
    }
    $orig = @{}; foreach ($sec in $order) { foreach ($k in $want[$sec].Keys) { $orig["$sec|$k"] = $null } }
    $out = New-Object System.Collections.Generic.List[string]; $diff = New-Object System.Collections.Generic.List[string]
    $seen = @{}; $secSeen = @{}; $cur = $null
    $flush = {
        if ($null -ne $cur -and $want.ContainsKey($cur)) {
            $blank = 0; while ($out.Count -gt 0 -and $out[$out.Count - 1].Trim() -eq '') { $out.RemoveAt($out.Count - 1); $blank++ }
            foreach ($k in $want[$cur].Keys) {
                $v = $want[$cur][$k]
                if ($null -ne $v -and -not $seen.ContainsKey("$cur|$k")) { $out.Add("$k=$v"); $diff.Add("[$cur] +$k=$v"); $seen["$cur|$k"] = 1 }
            }
            for ($i = 0; $i -lt $blank; $i++) { $out.Add('') }
        }
    }
    foreach ($ln in [regex]::Split($text, '\r?\n')) {
        $s = $ln.Trim()
        if ($s -match '^\[(.+)\]$') { . $flush; $cur = $Matches[1]; $secSeen[$cur] = 1; $out.Add($ln); continue }
        if ($null -ne $cur -and $want.ContainsKey($cur) -and $s -match '^([^=;#]+?)\s*=(.*)$' -and $want[$cur].Contains($Matches[1])) {
            $k = $Matches[1]; $v = $Matches[2]; $w = $want[$cur][$k]
            if (-not $seen.ContainsKey("$cur|$k")) { $orig["$cur|$k"] = $v }
            $seen["$cur|$k"] = 1
            if ($null -eq $w) { $diff.Add("[$cur] -$k"); continue }
            if ($v -ne [string]$w) { $diff.Add("[$cur] $k $v->$w"); $ln = "$k=$w" }
        }
        $out.Add($ln)
    }
    . $flush
    for ($i = $out.Count - 1; $i -ge 0; $i--) {
        if ($out[$i].Trim() -notmatch '^\[(.+)\]$' -or $DropEmpty -notcontains $Matches[1]) { continue }
        $name = $Matches[1]
        $j = $i + 1; while ($j -lt $out.Count -and $out[$j].Trim() -eq '') { $j++ }
        if ($j -ge $out.Count -or $out[$j].Trim() -match '^\[.+\]$') { $diff.Add("-[$name]"); $out.RemoveAt($i) }
    }
    # New sections go before the file's trailing newline, so the file keeps ending the way it did.
    $tail = 0; while ($out.Count -gt 1 -and $out[$out.Count - 1] -eq '') { $out.RemoveAt($out.Count - 1); $tail++ }
    foreach ($sec in $order) {
        if ($secSeen.ContainsKey($sec)) { continue }
        $adds = @($want[$sec].Keys | Where-Object { $null -ne $want[$sec][$_] })
        if ($adds) { $out.Add("[$sec]"); foreach ($k in $adds) { $out.Add("$k=$($want[$sec][$k])"); $diff.Add("[$sec] +$k=$($want[$sec][$k])") } }
    }
    for ($i = 0; $i -lt $tail; $i++) { $out.Add('') }
    if ($Write -and $diff.Count) {
        $f = Get-Item -LiteralPath $Path -Force; if ($f.IsReadOnly) { $f.IsReadOnly = $false }
        $body = $enc.GetBytes(($out -join $nl))
        $pre = [byte[]]@(); if ($skip -eq 2) { $pre = [byte[]](0xFF, 0xFE) } elseif ($skip -eq 3) { $pre = [byte[]](0xEF, 0xBB, 0xBF) }
        $tmp = "$Path.adtmp"
        [IO.File]::WriteAllBytes($tmp, [byte[]]($pre + $body))
        [IO.File]::Replace($tmp, $Path, [NullString]::Value)
    }
    $o = @(); foreach ($key in $orig.Keys) { $i = $key.IndexOf('|'); $o += , @($key.Substring(0, $i), $key.Substring($i + 1), $orig[$key]) }
    @{ Diff = @($diff); Original = $o; Sections = @($secSeen.Keys) }
}

# ------------------------------------------------------------------ JSON settings (json-set)
# Text of a JSON file with its encoding: a BOM decides, otherwise strict UTF-8 (anything else is refused).
function Read-AdTextFile([string]$path) {
    $raw = [IO.File]::ReadAllBytes($path); $skip = 0; $pre = [byte[]]@()
    if ($raw.Length -ge 3 -and $raw[0] -eq 0xEF -and $raw[1] -eq 0xBB -and $raw[2] -eq 0xBF) { $enc = New-Object Text.UTF8Encoding $false, $true; $skip = 3 }
    elseif ($raw.Length -ge 2 -and $raw[0] -eq 0xFF -and $raw[1] -eq 0xFE) { $enc = [Text.Encoding]::Unicode; $skip = 2 }
    else { $enc = New-Object Text.UTF8Encoding $false, $true }
    if ($skip) { $pre = [byte[]]$raw[0..($skip - 1)] }
    try { $text = $enc.GetString($raw, $skip, $raw.Length - $skip) } catch { throw "$path is not valid UTF-8 or UTF-16 text" }
    @{ Text = $text; Enc = $enc; Pre = $pre }
}
# Writes through a temp file and [IO.File]::Replace, keeping the original BOM and encoding.
function Write-AdTextFile([string]$path, [string]$text, $doc) {
    $f = Get-Item -LiteralPath $path -Force; if ($f.IsReadOnly) { $f.IsReadOnly = $false }
    $tmp = "$path.adtmp"
    [IO.File]::WriteAllBytes($tmp, [byte[]]($doc.Pre + $doc.Enc.GetBytes($text)))
    [IO.File]::Replace($tmp, $path, [NullString]::Value)
}
