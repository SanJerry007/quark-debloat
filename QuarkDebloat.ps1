.SYNOPSIS
  Debloat Quark / Quark Netdisk: block its ads, popups, AI add-ons, promotions, telemetry and self-updaters
  while keeping its core function. Generated by app-debloat from a manifest; edit the manifest, not this file.

.DESCRIPTION
  Dry run by default: resolves the install, prints how it was found (registry view and Uninstall key, environment
  variable, service, candidate or -InstallRoot) and which vendor identity check passed, prints the exact plan and
  changes nothing. After the plan it lists every option that was not selected, with the action ids it would
  enable or skip and their evidence.
  -Apply executes exactly the printed plan (elevated PowerShell). Idempotent: a second run plans nothing.
  Pass at most one of -Apply, -Install, -Uninstall, -Auto; a combination is refused before anything runs.
  Every change is journaled before it is made, with the state it replaced (first run wins) and the state it
  writes, under %ProgramData%\AppDebloat\quark\journal.jsonl. -Uninstall replays that journal in reverse and
  restores an original only where the current state is still the one this script wrote.
  Actions backed only by inferred or hypothesis evidence are INACTIVE: the plan lists them with the option that
  enables them. Versions not listed in the manifest are refused by -Apply, -Install and -Auto unless -Force.
  Planned items that a recorded knownFailure covers are marked and counted apart ("N change(s) planned, K of them
  known to fail"). Without elevation, scheduled tasks that only SYSTEM or Administrators can read are invisible:
  every task search then says so, and when an elevated enumeration was saved to
  %ProgramData%\AppDebloat\quark\elevated-tasks.json it also prints that list's match count and date.
  Exit code: 0 ok, 1 a step failed or -Uninstall left items behind, 2 refused before any change (more than one
  mode, not elevated, not installed, identity check failed, unsupported version, bad manifest).

.PARAMETER Apply
  Execute the plan. Needs an elevated PowerShell.

.PARAMETER Install
  Apply now and keep it applied. Runs the apply first; only when it had no failures (failures recorded as
  knownFailure in the manifest are WARN and do not count) it copies this file and the chosen options to
  %ProgramData%\AppDebloat\quark (admin-only) and registers the task QuarkDebloat-Watch (at logon and
  every 6 hours), which re-confirms only the blocking actions. Otherwise it registers nothing, says why and exits 1.
  Install only after the core-function checks passed.

.PARAMETER Uninstall
  Undo the journal in reverse order: restores each original only if the current state is still what this script
  wrote (otherwise CONFLICT, left alone), removes only the tasks, IFEO values, firewall rules and browser policy
  values it recorded, restores replaced vendor files from the backup taken before the change, re-creates registry
  values it deleted while they are still absent, and puts back INI and JSON values (a settings file whose owner
  exe is running is a WARN: close the app and run it again). Any WARN, CONFLICT or failure keeps the journal and
  the state folder and exits 1; run it again after resolving them.

.PARAMETER Auto
  Used by the QuarkDebloat-Watch task: saved options, blocking actions only, full log to auto.log and one
  compact line per run to history.log (known failures as [action-id xN, ref R], whose full text stays in auto.log;
  then the text of each failure as FAIL: <item :: error>, unique and cut to about 200 characters; then the WARN text).
  Placeholders it placed earlier that were deleted since are re-created while their parent folder exists.
  On a version the manifest does not list it changes nothing, logs a WARN line and exits 2.

.PARAMETER InstallRoot
  Use this folder as the install root instead of resolving it. It must still pass the manifest's vendor
  identity checks (expected files, signer, content), and its real path (junctions resolved) is what is checked.

.PARAMETER Force
  Apply, install or auto-apply even when the installed version is not in the manifest's supported list.

.PARAMETER IgnoreUninspectable
  Process names (wildcards allowed, .exe optional) that the loaded-module check skips when they cannot be
  inspected, for a deferral you have checked is safe. Processes that can be inspected are always checked. The
  skipped processes are printed and journaled with each change they allowed. This run only: the watch task does
  not get it; list such processes in the manifest's checkLoadedExempt instead.

