    if ($sg -and (-not @(AdGet $sg 'files' @()).Count -or -not (AdGet $sg 'subject'))) { $err.Add('installRoot.identity.signer needs files[] and subject') }
    $sup = AdGet (AdGet $m 'version') 'supported'
    $vers = @(AdGet $sup 'versions' @() | Where-Object { "$_".Trim() })
    $range = (AdGet $sup 'allowRange' $false) -and (AdGet $sup 'min') -and (AdGet $sup 'max')
    if (-not $vers.Count -and -not $range) { $err.Add('version.supported.versions must list the observed versions (a min/max range only with allowRange: true)') }
    # version.sources is a flat list of {source, ...}. A nested shape such as {file: {path}} silently resolves no
    # version and would make every Apply refuse, so reject anything that is not exactly the documented form.
    $srcs = @(AdGet (AdGet $m 'version') 'sources' @())
    if (-not $srcs.Count) { $err.Add('version.sources must list at least one source, e.g. {"source":"file","path":"{root}\\App.exe"}') }
    foreach ($f in 'files', 'preserve', 'processes', 'restartable', 'services') {
        foreach ($x in @(AdGet (AdGet $m 'core') $f @())) { if ($x -isnot [string] -or -not $x.Trim()) { $err.Add("core.$f entries must be non-empty strings") } }
    }
    $need = @{ registry = @('path'); uninstall = @(); file = @('path'); dirname = @(); text = @('path', 'regex') }
    foreach ($s in $srcs) {
        $k = AdGet $s 'source'
        if (-not $k -or -not $need.ContainsKey("$k")) { $err.Add("version.sources entry $(ConvertTo-Json $s -Compress) must be {""source"": one of $($need.Keys -join '/'), ...}"); continue }
        foreach ($f in $need["$k"]) { if (-not (AdGet $s $f)) { $err.Add("version.sources '$k' entry needs '$f'") } }
    }
    $opts = @(AdGet $m 'options' @()); $optNames = @($opts | ForEach-Object { AdGet $_ 'name' })
    foreach ($o in $optNames) { if ($o -notmatch '^[A-Z][A-Za-z0-9]{1,30}$' -or @('Apply', 'Install', 'Uninstall', 'Auto', 'InstallRoot', 'Force', 'IgnoreUninspectable') -contains $o) { $err.Add("bad option name '$o'") } }
    foreach ($x in @(AdGet $m 'checkLoadedExempt' @())) {
        if ($x -isnot [string] -or $x -notmatch '^[\w\.\-\*\? ]+$' -or $x -notmatch '[\w]') { $err.Add("checkLoadedExempt entries are process names (wildcards allowed, not only wildcards): '$x'") }
    }
    $ids = @{}
    foreach ($a in @(AdGet $m 'actions' @())) {
        $id = AdGet $a 'id'; $t = AdGet $a 'type'
        if (-not $id) { $err.Add('action without id'); continue }
        if ($ids.ContainsKey($id)) { $err.Add("duplicate action id $id") }; $ids[$id] = 1
        if ($script:AdTypes -notcontains $t) { $err.Add("$id`: unknown type '$t'") }
        if ($script:AdCategories -notcontains (AdGet $a 'category')) { $err.Add("$id`: category must be one of $($script:AdCategories -join '/')") }
        if (-not @(AdGet $a 'rationale' @()).Count) { $err.Add("$id`: rationale (ledger item ids) is required") }
        if ((AdGet $a 'reapply' $false) -and (AdGet $a 'effect' 'block') -eq 'reset') { $err.Add("$id`: reapply must be false for effect=reset") }
        foreach ($g in 'when', 'unless') { $v = AdGet $a $g; if ($v -and $optNames -notcontains $v) { $err.Add("$id`: $g references unknown option '$v'") } }
        $ev = AdGet $a 'evidence'
        if ($script:AdEvidence -notcontains $ev) { $err.Add("$id`: evidence must be one of $($script:AdEvidence -join '/') (the weakest ledger status in its rationale)") }
        elseif ($script:AdEvidenceActive -notcontains $ev) {
            $w = AdGet $a 'when'
            if (-not $w) { $err.Add("$id`: evidence '$ev' needs 'when' naming the option that enables it (inactive by default)") }
            else {
                $opt = @($opts | Where-Object { (AdGet $_ 'name') -eq $w })[0]
                if ($opt -and (AdGet $opt 'default' $false)) { $err.Add("$id`: option '$w' gates $ev evidence and must default to false") }
            }
            if (AdGet $a 'unless') { $err.Add("$id`: an $ev action is enabled only by 'when', not 'unless'") }
        }
        if ($t -eq 'hook' -and -not (AdGet $a 'hook')) { $err.Add("$id`: hook name missing") }
        $kf = AdGet $a 'knownFailure'
        if ($null -ne $kf -and (-not "$(AdGet $kf 'reason' '')".Trim() -or -not "$(AdGet $kf 'ref' '')".Trim())) { $err.Add("$id`: knownFailure needs 'reason' (why it fails) and 'ref' (ledger item or verification note)") }
        $ktp = if ($null -ne $kf) { $kf.PSObject.Properties['targets'] }   # read directly: AdGet would return [] as $null
        if ($ktp) {
            $kt = $ktp.Value
            if ($null -eq $kt -or -not @($kt).Count -or @(@($kt) | Where-Object { $_ -isnot [string] -or -not $_.Trim() }).Count) { $err.Add("$id`: knownFailure.targets must list target names or patterns (leave it out to cover the whole action)") }
            if (@('hosts-block', 'preboot-file-edit') -contains $t) { $err.Add("$id`: $t plans one item per action, so its knownFailure cannot list targets; leave targets out") }
        }
        if ($t -eq 'task-disable') {
            $tp = AdGet $a 'taskPath'
            if ($tp) {
                $why = Get-AdTaskPathRefusal ([string]$tp); if ($why) { $err.Add("$id`: $why") }
                foreach ($x in @(AdGet $a 'target' @())) { if ("$x" -match '\\') { $err.Add("$id`: with taskPath, target lists task name patterns without a folder: '$x'") } }
            } elseif (-not @(AdGet $a 'target' @()).Count) { $err.Add("$id`: task-disable needs target (\Folder\Name*) or taskPath") }
        }
        if ($t -eq 'ini-set' -or $t -eq 'json-set') {
            if (-not (AdGet $a 'path')) { $err.Add("$id`: $t needs 'path'") }
            if ($null -eq $a.PSObject.Properties['value']) { $err.Add("$id`: $t needs 'value'$(if ($t -eq 'ini-set') { ' (null removes the key)' })") }
            foreach ($x in @(AdGet $a 'onlyWhenNotRunning' @())) { if ($x -isnot [string] -or $x -notmatch '\.exe$') { $err.Add("$id`: onlyWhenNotRunning lists exe paths") } }
        }
        if ($t -eq 'ini-set') {
            if (-not (AdGet $a 'section') -or -not (AdGet $a 'key')) { $err.Add("$id`: ini-set needs 'section' and 'key'") }
            $v = AdGet $a 'value'
            if ($null -ne $v -and $v -isnot [string] -and -not ($v -is [int] -or $v -is [long] -or $v -is [double] -or $v -is [decimal])) { $err.Add("$id`: ini-set value must be a string, a number or null") }
            $enc = AdGet $a 'encoding' ''
            if ($enc -and @('auto', 'utf-8', 'utf-16le') -notcontains $enc) {
                try { $cp = 0; if ([int]::TryParse($enc, [ref]$cp)) { [void][Text.Encoding]::GetEncoding($cp) } else { [void][Text.Encoding]::GetEncoding($enc) } }
                catch { $err.Add("$id`: unknown encoding '$enc' (auto, utf-8, utf-16le, or a code page name or number)") }
            }
        }
        if ($t -eq 'json-set') {
            $ptr = AdGet $a 'pointer' ''
            if ($ptr -notmatch '^/.') { $err.Add("$id`: json-set needs 'pointer', a JSON pointer such as /browser/show_ads") }
            elseif (@($ptr.Substring(1).Split('/')) -contains '-') { $err.Add("$id`: json-set pointer may not use '-' (array append)") }
        }
        if ($t -eq 'reg-set') {
            $k = AdGet $a 'kind' 'DWord'
            if ($script:AdRegKinds -notcontains $k) { $err.Add("$id`: kind must be one of $($script:AdRegKinds -join ', ')") }
            elseif ($k -eq 'Binary') {
                $vs = AdGet $a 'values'; $bv = if ($vs) { @($vs.PSObject.Properties | ForEach-Object { $_.Value }) } else { @(, (AdGet $a 'value')) }
                foreach ($v in $bv) { $ok = $v -is [string]; if ($ok) { try { [void](ConvertTo-AdHex $v) } catch { $ok = $false } }; if (-not $ok) { $err.Add("$id`: a Binary value is a hex byte string such as ""03 00 00 00"": '$v'") } }
            }
        }
        if ($t -eq 'reg-delete-key') {
            foreach ($f in 'match', 'matchDefault') { if ($null -ne (AdGet $a $f)) { $why = Get-AdRegexRefusal (AdGet $a $f) $f; if ($why) { $err.Add("$id`: $why") } } }
        }
        if ($t -eq 'reg-delete-value') {
            $tg = @(AdGet $a 'target' @())
            if (-not $tg.Count -or @($tg | Where-Object { $_ -isnot [string] -or $_ -notmatch '^(?i)(HKLM|HKEY_LOCAL_MACHINE|HKLM:|HKCU|HKEY_CURRENT_USER|HKCU:)\\.' }).Count) { $err.Add("$id`: target lists registry keys (HKLM\... or HKCU\..., * and ? allowed in a segment)") }
            $np = $a.PSObject.Properties['names']; $mx = AdGet $a 'match'
            if ([bool]$np -eq ($null -ne $mx)) { $err.Add("$id`: reg-delete-value needs exactly one of names[] or match") }
            if ($np -and (-not @($np.Value).Count -or @(@($np.Value) | Where-Object { $_ -isnot [string] -or -not $_ }).Count)) { $err.Add("$id`: names lists value names (the default value is never deleted)") }
            if ($null -ne $mx) { $why = Get-AdRegexRefusal $mx 'match'; if ($why) { $err.Add("$id`: $why") } }
        }
        if ($t -eq 'browser-ext-block') {
            $xs = @(AdGet $a 'ids' @())
            if (-not $xs.Count -or @($xs | Where-Object { $_ -isnot [string] -or $_ -cnotmatch '^[a-p]{32}$' }).Count) { $err.Add("$id`: ids lists extension ids (32 lowercase letters a to p)") }
            $dup = @($xs | Group-Object | Where-Object { $_.Count -gt 1 } | ForEach-Object { $_.Name })
            if ($dup.Count) { $err.Add("$id`: ids lists $($dup -join ', ') more than once") }
            $bp = $a.PSObject.Properties['browsers']
            if ($bp -and (-not @($bp.Value).Count -or @(@($bp.Value) | Where-Object { -not $script:AdBrowsers.Contains("$_".ToLowerInvariant()) }).Count)) { $err.Add("$id`: browsers lists $($script:AdBrowsers.Keys -join ' and/or ')") }
        }
        if ($t -eq 'firewall-block-program' -and @('Inbound', 'Outbound') -notcontains (AdGet $a 'direction' 'Outbound')) { $err.Add("$id`: direction must be Inbound or Outbound") }
        if ($t -eq 'hosts-block' -and (AdGet $a 'reapply' $false) -and -not (AdGet $a 'acknowledgeFlagging' $false)) { $err.Add("$id`: hosts-block needs acknowledgeFlagging") }
        if ($t -eq 'acl-deny-write' -and @('write', 'write+protect') -notcontains (AdGet $a 'rights' 'write')) { $err.Add("$id`: rights must be write (default) or write+protect") }
    }
    if ($err.Count) { throw ("invalid manifest: " + ($err -join '; ')) }
}

# ------------------------------------------------------------------ resolution
# Every Uninstall entry matched by displayName / publisher, in lookup order (HKLM 64, HKLM 32, HKCU), each with
# the registry view and key it came from.
function Find-AdUninstallEntries($rule) {
    $dn = AdGet $rule 'displayName'; $pub = AdGet $rule 'publisher'
    $found = New-Object System.Collections.Generic.List[object]
    if (-not $dn) { return $found }
    $sub = 'SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall'
    foreach ($spec in @(@('HKLM', 64), @('HKLM', 32), @('HKCU', 64))) {
        $b = Open-AdHive $spec[0] $spec[1]; $root = $b.OpenSubKey($sub)
        if ($root) {
            foreach ($n in $root.GetSubKeyNames()) {
                $k = $root.OpenSubKey($n); if (-not $k) { continue }
                $d = [string]$k.GetValue('DisplayName'); $p = [string]$k.GetValue('Publisher')
                if ($d -match $dn -and (-not $pub -or $p -match $pub)) {
                    $view = if ($spec[0] -eq 'HKCU') { '' } elseif ($spec[1] -eq 32) { ' (32-bit view)' } else { ' (64-bit view)' }
                    $found.Add(@{ DisplayName = $d; DisplayVersion = [string]$k.GetValue('DisplayVersion'); InstallLocation = [string]$k.GetValue('InstallLocation')
                                  DisplayIcon = [string]$k.GetValue('DisplayIcon'); UninstallString = [string]$k.GetValue('UninstallString')
                                  Where = "$($spec[0])\$sub\$n$view" })
                }
                $k.Close()
            }
            $root.Close()
        }
        $b.Close()
    }
    $found
}
# The program a command line starts (quoted path, or the text up to the first '.exe'), environment variables expanded.
function Get-AdCommandExe([string]$cmd) {
    if (-not $cmd) { return $null }
    $c = $cmd.Trim()
    if ($c.StartsWith('"')) { $j = $c.IndexOf('"', 1); if ($j -lt 0) { return $null }; $c = $c.Substring(1, $j - 1) } else { $c = ($c -split ',')[0]; if ($c -match '^(.+?\.exe)') { $c = $Matches[1] } }
    [Environment]::ExpandEnvironmentVariables($c)
}
function Get-AdDirFromCommand([string]$cmd) {
    $c = Get-AdCommandExe $cmd
    if (-not $c) { return $null }
    try { [IO.Path]::GetDirectoryName($c) } catch { $null }
}
# Vendor identity of a candidate root. Applies to every source, including -InstallRoot and the environment
# variable, so an override cannot point at a look-alike folder. Returns @{ Refusal = $null or the reason;
# Summary = what passed, for the header }.
function Test-AdRootIdentity($r, [string]$d) {
    $id = AdGet $r 'identity'; $ok = @()
    $no = { param($why) @{ Refusal = $why; Summary = $null } }
    foreach ($f in @(AdGet $id 'files' @())) { if (-not (Test-Path -LiteralPath (Join-Path $d $f))) { return (& $no "expected file $f is missing") } }
    if (@(AdGet $id 'files' @()).Count) { $ok += "files present: $(@(AdGet $id 'files' @()) -join ', ')" }
    foreach ($t in @(AdGet $id 'text' @())) {
        $f = AdGet $t 'file'; $p = Join-Path $d $f
        if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { return (& $no "identity file $f is missing") }
        if ([IO.File]::ReadAllText($p) -notmatch (AdGet $t 'regex')) { return (& $no "identity file $f does not match /$(AdGet $t 'regex')/") }
        $ok += "text check $f matches /$(AdGet $t 'regex')/"
    }
    $sg = AdGet $id 'signer'
    if ($sg) {
        $subjects = @()
        foreach ($f in @(AdGet $sg 'files' @())) {
            $p = Join-Path $d $f
            if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { return (& $no "signed file $f is missing") }
            $s = Get-AuthenticodeSignature -LiteralPath $p
            if ("$($s.Status)" -ne 'Valid') { return (& $no "$f signature status is $($s.Status)") }
            if ($s.SignerCertificate.Subject -notmatch (AdGet $sg 'subject')) { return (& $no "$f is signed by '$($s.SignerCertificate.Subject)', expected /$(AdGet $sg 'subject')/") }
            $subjects += $s.SignerCertificate.Subject
        }
        $ok += "signer '$(@($subjects | Select-Object -Unique) -join "', '")' on $(@(AdGet $sg 'files' @()) -join ', ')"
    }
    @{ Refusal = $null; Summary = ($ok -join '; ') }
}
function Get-AdRootIdentityRefusal($r, [string]$d) { (Test-AdRootIdentity $r $d).Refusal }
# Returns @(root, how it was found, identity summary). Sets $script:Ad.Uninstall to the Uninstall entry that belongs
# to the chosen root (used by the 'uninstall' version source), or $null when none clearly does.
function Resolve-AdInstallRoot($m, [string]$override) {
    $r = AdGet $m 'installRoot'
    $must = @(AdGet $r 'mustContain' @())
    $cands = New-Object System.Collections.Generic.List[object]
    $mk = { param($src, $path, $explicit, $entry) $cands.Add(@{ Source = $src; Path = $path; Explicit = $explicit; Entry = $entry }) }
    if ($override) { & $mk '-InstallRoot override' $override $true $null }
    $ev = AdGet $r 'envVar'
    if ($ev -and [Environment]::GetEnvironmentVariable($ev)) { & $mk "environment variable $ev" ([Environment]::GetEnvironmentVariable($ev)) $true $null }
    $entries = @()
    $u = AdGet $r 'uninstall'
    if ($u) {
        $entries = @(Find-AdUninstallEntries $u)
        $locs = @($entries | Where-Object { $_.InstallLocation } | ForEach-Object { $_.InstallLocation.Trim().Trim('"').TrimEnd('\') } | Sort-Object -Unique)
        if ($locs.Count -gt 1) {
            Say 'WARN' "uninstall.displayName /$(AdGet $u 'displayName')/ matches $($entries.Count) entries with different InstallLocation values; each is tried in this order and must pass mustContain and identity (narrow the regex or add publisher):"
            foreach ($e in $entries) { Write-Host ("         - '{0}' {1} at '{2}' [{3}]" -f $e.DisplayName, $e.DisplayVersion, $e.InstallLocation, $e.Where) }
        }
        foreach ($e in $entries) {
            $tag = "'$($e.DisplayName)' ($($e.Where))"
            if ($e.InstallLocation) { & $mk "Uninstall InstallLocation of $tag" $e.InstallLocation $false $e }
            $d = Get-AdDirFromCommand $e.DisplayIcon; if ($d) { & $mk "Uninstall DisplayIcon of $tag" $d $false $e }
            $d = Get-AdDirFromCommand $e.UninstallString; if ($d) { & $mk "Uninstall UninstallString of $tag" $d $false $e }
        }
    }
    $sv = AdGet $r 'service'
    if ($sv) {
        $name = AdGet $sv 'name'
        $s = $null; try { $s = Get-AdService $name } catch { Say 'WARN' "service query for $name failed ($($_.Exception.Message)); not used to find the install root" }
        if ($s) {
            $d = Get-AdDirFromCommand $s.PathName
            for ($i = 0; $i -lt [int](AdGet $sv 'levelsUp' 0) -and $d; $i++) { $d = [IO.Path]::GetDirectoryName($d) }
            if ($d) { & $mk "service $name ImagePath" $d $false $null }
        }
    }
    foreach ($c in @(AdGet $r 'candidates' @())) { & $mk "candidate $c" ([Environment]::ExpandEnvironmentVariables($c)) $false $null }
    foreach ($c in $cands) {
        $d = $c.Path.Trim().Trim('"'); $explicit = $c.Explicit
        $missing = @($must | Where-Object { -not (Test-Path -LiteralPath (Join-Path $d $_)) })
        if (-not (Test-Path -LiteralPath $d -PathType Container) -or $missing) {
            # An explicit override that does not fit is an error, never a silent fall-through to another root.
            if ($explicit) { throw "install root '$d' (from $($c.Source)) is not $(AdGet $m 'name'): missing $(if ($missing) { $missing -join ', ' } else { 'the folder' })" }
            continue
        }
        $idr = Test-AdRootIdentity $r $d
        if ($idr.Refusal) {
            if ($explicit) { throw "install root '$d' (from $($c.Source)) fails the vendor identity check: $($idr.Refusal)" }
            Say 'WARN' "candidate root $d (from $($c.Source)) fails the vendor identity check: $($idr.Refusal)"; continue
        }
        $root = Get-AdNormal $d
        $entry = $c.Entry
        if (-not $entry) {
            $own = @($entries | Where-Object { $_.InstallLocation -and $(try { (Get-AdNormal $_.InstallLocation.Trim().Trim('"')) -ieq $root } catch { $false }) })
            if ($own.Count) { $entry = $own[0] } elseif ($entries.Count -eq 1) { $entry = $entries[0] }
        }
        $script:Ad.Uninstall = $entry
        return @($root, $c.Source, $idr.Summary)
    }
    throw "$(AdGet $m 'name') is not installed (no candidate root contains $($must -join ', ') and passes the identity check)."
}
function Resolve-AdVersionDir($m, [string]$root) {
    $vd = AdGet $m 'versionDir'
    if (-not $vd) { return $root }
    $must = AdGet $vd 'mustContain' ''
    $reg = AdGet $vd 'registry'
    if ($reg) {
        $hp = Split-AdRegPath (AdGet $reg 'path')
        $v = Get-AdRegValue $hp[0] (AdGet $reg 'view' 64) $hp[1] (AdGet $reg 'name' 'Version')
        if ($v.exists -and (Test-Path -LiteralPath (Join-Path (Join-Path $root $v.value) $must))) { return (Join-Path $root $v.value) }
    }
    $pat = AdGet $vd 'pattern' '.'
    $d = @(Get-ChildItem -LiteralPath $root -Directory -ErrorAction SilentlyContinue | Where-Object {
            $_.Name -match $pat -and (-not $must -or (Test-Path -LiteralPath (Join-Path $_.FullName $must))) } |
        Sort-Object { $x = $null; if ([version]::TryParse($_.Name, [ref]$x)) { $x } else { [version]'0.0' } }, Name -Descending)
    if (-not $d) { throw "no version directory matching '$pat' with '$must' under $root" }
    $d[0].FullName
}
function Get-AdVersion($m) {
    $v = AdGet $m 'version'
    foreach ($s in @(AdGet $v 'sources' @())) {
        try {
            switch (AdGet $s 'source') {
                'registry' { $hp = Split-AdRegPath (AdGet $s 'path'); $r = Get-AdRegValue $hp[0] (AdGet $s 'view' 64) $hp[1] (AdGet $s 'name' 'Version'); if ($r.exists -and $r.value) { return "$($r.value)" } }
                'uninstall' { if ($script:Ad.Uninstall -and $script:Ad.Uninstall.DisplayVersion) { return $script:Ad.Uninstall.DisplayVersion } }
                'file' { $p = Expand-AdPath (AdGet $s 'path'); if (Test-Path -LiteralPath $p -PathType Leaf) { $fv = (Get-Item -LiteralPath $p).VersionInfo.FileVersion; if ($fv) { return ($fv -replace ',', '.' -replace '\s', '') } } }
                'dirname' { if ($script:Ad.Ver -ne $script:Ad.Root) { return (Split-Path -Leaf $script:Ad.Ver) } }
                'text' { $p = Expand-AdPath (AdGet $s 'path'); if (Test-Path -LiteralPath $p -PathType Leaf) { $t = [IO.File]::ReadAllText($p); if ($t -match (AdGet $s 'regex')) { return $Matches[1] } } }
            }
        } catch { }
    }
    $null
}
# Supported means: listed in version.supported.versions (the versions actually inspected), or, only when the
# manifest opts in with allowRange, inside min..max. An unknown version is never supported.
function Test-AdVersionSupported([string]$ver, $m) {
    $sup = AdGet (AdGet $m 'version') 'supported'
    if (-not $sup -or -not $ver) { return $false }
    $v = $ver.Trim(); $x = $null; $vx = [version]::TryParse(($v -replace '[^\d\.].*$', ''), [ref]$x)
    foreach ($s in @(AdGet $sup 'versions' @())) {
        $s = "$s".Trim(); if (-not $s) { continue }
        if ($s -ieq $v) { return $true }
        $y = $null; if ($vx -and $s -match '^[\d\.]+$' -and [version]::TryParse($s, [ref]$y) -and $x -eq $y) { return $true }
    }
    if ((AdGet $sup 'allowRange' $false) -and $vx) {
        $min = AdGet $sup 'min'; $max = AdGet $sup 'max'
        if ($min -and $max -and $x -ge [version]$min -and $x -le [version]$max) { return $true }
    }
    $false
}

# ------------------------------------------------------------------ journal
# journal.jsonl is append-only. A 'change' line is written BEFORE the mutation it describes (write-ahead): it
# carries the original state (first line for a key wins) and the state the tool is about to write ('after').
# An 'undone' line closes a key, so an interrupted -Uninstall never replays a finished restore.
function Protect-AdStateDir {
    $d = $script:Ad.StateDir
    if (-not (Test-Path -LiteralPath $d)) { New-Item -ItemType Directory -Path $d -Force | Out-Null }
    Invoke-AdNative icacls.exe @($d, '/inheritance:r', '/grant:r', '*S-1-5-18:(OI)(CI)F', '*S-1-5-32-544:(OI)(CI)F', '*S-1-5-32-545:(OI)(CI)RX') | Out-Null
}
function Add-AdJournalLine($e) {
    if (-not (Test-Path -LiteralPath $script:Ad.StateDir)) { Protect-AdStateDir }
    [IO.File]::AppendAllText($script:Ad.JournalPath, ((ConvertTo-Json -InputObject $e -Compress -Depth 10) + "`r`n"), (New-Object Text.UTF8Encoding $false))
}
# Active entries, oldest first: one per key, with the first-seen original and the latest after-state.
function Read-AdJournal {
    $active = [ordered]@{}
    if (Test-Path -LiteralPath $script:Ad.JournalPath) {
        foreach ($ln in [IO.File]::ReadAllLines($script:Ad.JournalPath)) {
            if (-not $ln.Trim()) { continue }
            $e = $ln | ConvertFrom-Json
            $k = [string](AdGet $e 'key')
            if ((AdGet $e 'kind' 'change') -eq 'note') { continue }      # a recorded choice, nothing to undo
            if ((AdGet $e 'kind' 'change') -eq 'undone') { if ($active.Contains($k)) { $active.Remove($k) }; continue }
            if ($active.Contains($k)) {
                $active[$k] | Add-Member -NotePropertyName after -NotePropertyValue (AdGet $e 'after') -Force
                $active[$k] | Add-Member -NotePropertyName data -NotePropertyValue (AdGet $e 'data') -Force
            } else {
                if ($null -eq $e.PSObject.Properties['after']) { $e | Add-Member -NotePropertyName after -NotePropertyValue $null }
                $active[$k] = $e
            }
        }
    }
    $list = New-Object System.Collections.Generic.List[object]
    foreach ($v in $active.Values) { $list.Add($v) }
    $list
}
