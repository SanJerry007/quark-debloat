function Get-AdActionPlan($a) {
    $items = New-Object System.Collections.Generic.List[object]
    $type = AdGet $a 'type'; $id = AdGet $a 'id'
    switch ($type) {
        'service-disable' {
            foreach ($n in @(AdGet $a 'target' @())) {
                if ($script:Ad.CoreSvcs -contains $n.ToLowerInvariant()) { throw "core-function contract protects service $n" }
                $s = Get-AdService $n
                if (-not $s) { Say 'SKIP' "service $n not present"; continue }
                if ($s.StartMode -eq 'Disabled') { Say 'SKIP' "service $n already disabled"; continue }
                $items.Add((New-AdItem $a 'service' "svc:$n" "Disable service $n (was $($s.StartMode), $($s.State))" @{ name = $n; stop = [bool](AdGet $a 'stop' $true) } `
                    @{ startMode = "$($s.StartMode)"; state = "$($s.State)"; delayed = [bool](AdGet $s 'DelayedAutoStart' $false) } ([ordered]@{ startMode = 'Disabled' })))
            }
        }
        'task-disable' {
            # target: '\Folder\Name*' (that folder only); or taskPath (a folder, matched with its subfolders) plus
            # target name patterns (default '*'). Every search prints its match count, so a miss is visible.
            $specs = @(); $tpr = AdGet $a 'taskPath'
            if ($tpr) {
                $why = Get-AdTaskPathRefusal ([string]$tpr); if ($why) { throw $why }
                $tf = Get-AdTaskFolder ([string]$tpr); $names = @(AdGet $a 'target' @()); if (-not $names.Count) { $names = @('*') }
                foreach ($n in $names) { $specs += , @($tf, [string]$n, $true) }
            } else {
                foreach ($t in @(AdGet $a 'target' @())) {
                    $i = $t.LastIndexOf('\'); $tp = if ($i -ge 0) { $t.Substring(0, $i + 1) } else { '\' }
                    $specs += , @((Get-AdTaskFolder $tp), $t.Substring($i + 1), $false)
                }
            }
            foreach ($sp in $specs) {
                $found = @(Get-AdTasks $sp[0] $sp[1] -Recurse:$sp[2] | Where-Object { $_.TaskName -notlike "$($script:Ad.Prefix)Debloat-*" -and $_.TaskPath -notlike '\Microsoft\*' })
                $where = if ($sp[2]) { "$($sp[0]) and its subfolders" } else { "$($sp[0]) (this folder only; taskPath also searches subfolders)" }
                Say 'INFO' ("$id`: searched $where for $($sp[1]): $($found.Count) match$(if ($found.Count -ne 1) { 'es' })" + $(if ($found.Count) { " ($((@($found | ForEach-Object { "$($_.TaskPath)$($_.TaskName)" }) | Select-Object -First 5) -join ', '))" } else { '' }) +
                    (Get-AdTaskSearchNote $sp[0] $sp[1] $sp[2]))
                foreach ($f in $found) {
                    if ("$($f.State)" -eq 'Disabled') { Say 'SKIP' "task $($f.TaskPath)$($f.TaskName) already disabled"; continue }
                    $ti = Get-AdTaskIdentity $f
                    $items.Add((New-AdItem $a 'task' "task:$($f.TaskPath)$($f.TaskName)" "Disable scheduled task $($f.TaskPath)$($f.TaskName)" @{ path = $f.TaskPath; name = $f.TaskName } `
                        @{ state = "$($f.State)"; actions = $ti } ([ordered]@{ state = 'Disabled'; actions = $ti })))
                }
            }
        }
        'file-placeholder-dir' {
            $create = [bool](AdGet $a 'createIfMissing' $false); $bk = [bool](AdGet $a 'backup' $true)
            foreach ($f in (Get-AdTargets $a)) {
                Assert-AdPathSafe $f
                if (Test-Path -LiteralPath $f -PathType Container) { Say 'SKIP' "$f is already a placeholder directory"; continue }
                if (Test-Path -LiteralPath $f -PathType Leaf) {
                    $fi = Get-Item -LiteralPath $f -Force
                    $items.Add((New-AdItem $a 'file2dir' "fs:$f" "Replace file with placeholder directory: $f" @{ path = $f; backup = $bk; stopHosts = @(@(AdGet $a 'stopHosts' @()) | ForEach-Object { Expand-AdPath $_ }) } `
                        @{ existed = $true; size = $fi.Length; sha256 = (Get-AdSha256 $f); fileVersion = $fi.VersionInfo.FileVersion; backup = $null } ([ordered]@{ kind = 'emptyDir' })))
                } elseif ($create -and $f -notmatch '[\*\?]' -and -not ($script:Ad.Journal.Contains("fs:$f") -and (AdGet $script:Ad.Journal["fs:$f"] 'actionId') -eq $id)) {
                    # A path journaled under this action is re-created by Get-AdPlaceholderRedo (parent check included);
                    # that step reads only this action's entries, so one journaled under another id is pre-created here.
                    $items.Add((New-AdItem $a 'file2dir' "fs:$f" "Pre-create placeholder directory (blocks re-download): $f" @{ path = $f; backup = $false; stopHosts = @() } @{ existed = $false } ([ordered]@{ kind = 'emptyDir' })))
                }
            }
            foreach ($x in @(Get-AdPlaceholderRedo $a @($items | ForEach-Object { $_.Key }))) { $items.Add($x) }
        }
        'dir-placeholder-file' {
            $create = [bool](AdGet $a 'createIfMissing' $false); $bk = [bool](AdGet $a 'backup' $true); $chk = [bool](AdGet $a 'checkLoaded' $true)
            $hosts = @(@(AdGet $a 'stopHosts' @()) | ForEach-Object { Get-AdNormal (Expand-AdPath $_) })
            foreach ($d in (Get-AdTargets $a)) {
                Assert-AdPathSafe $d
                if (Test-Path -LiteralPath $d -PathType Leaf) { Say 'SKIP' "$d is already a placeholder file"; continue }
                if (Test-Path -LiteralPath $d -PathType Container) {
                    $note = ''
                    if ($chk) {
                        # Loaded modules are matched by full path under this folder. Hosts named in stopHosts are left
                        # out here because they are stopped right before the change, where the check runs again.
                        $lu = Get-AdLoadedUnder $d -ExcludeImages $hosts
                        Write-AdModuleExemptions $lu
                        if ($lu.Hits.Count) { Say 'WARN' "$d has modules loaded in running processes ($(@($lu.Hits | Select-Object -First 3) -join '; ')$(if ($lu.Hits.Count -gt 3) { "; +$($lu.Hits.Count - 3) more" })); deferred: close them (or add the host to stopHosts) or reboot, and run again"; continue }
                        if ($lu.Unknown.Count) {
                            if ($script:Ad.Mode -eq 'Plan' -and -not (Test-AdIsAdmin)) { $note = " [loaded-module check incomplete without elevation: $($lu.Unknown.Count) process(es) could not be inspected; -Apply checks again]" }
                            else { Say 'WARN' "${d}: $($lu.Unknown.Count) process(es) could not be inspected for loaded modules ($(@($lu.Unknown | Select-Object -First 3) -join '; ')); deferred, since unknown is never read as not loaded"; continue }
                        }
                    }
                    $files = @(Get-ChildItem -LiteralPath $d -Recurse -File -Force -ErrorAction Stop)
                    $bytes = 0; foreach ($x in $files) { $bytes += $x.Length }
                    $items.Add((New-AdItem $a 'dir2file' "fs:$d" "Replace folder with read-only placeholder file: $d ($($files.Count) files)$note" @{ path = $d; backup = $bk; checkLoaded = $chk; stopHosts = $hosts } `
                        @{ existed = $true; fileCount = $files.Count; bytes = $bytes; backup = $null } ([ordered]@{ kind = 'placeholderFile' })))
                } elseif ($create -and $d -notmatch '[\*\?]' -and -not ($script:Ad.Journal.Contains("fs:$d") -and (AdGet $script:Ad.Journal["fs:$d"] 'actionId') -eq $id)) {
                    $items.Add((New-AdItem $a 'dir2file' "fs:$d" "Pre-create read-only placeholder file (blocks re-download): $d" @{ path = $d; backup = $false; checkLoaded = $false; stopHosts = @() } @{ existed = $false } ([ordered]@{ kind = 'placeholderFile' })))
                }
            }
            foreach ($x in @(Get-AdPlaceholderRedo $a @($items | ForEach-Object { $_.Key }))) { $items.Add($x) }
        }
        'acl-deny-write' {
            $pr = AdGet $a 'principal' 'CurrentUser'
            $sid = switch ($pr) { 'CurrentUser' { [Security.Principal.WindowsIdentity]::GetCurrent().User.Value } 'Users' { 'S-1-5-32-545' } default { $pr } }
            if ($sid -notmatch '^S-1-[\d-]+$') { throw "principal must be CurrentUser, Users or a SID: $pr" }
            $prot = (AdGet $a 'rights' 'write') -eq 'write+protect'
            $want = if ($prot) { $script:AdDenyWriteRights -bor $script:AdDenyProtectRights } else { $script:AdDenyWriteRights }
            $deny = if ($prot) { 'write, delete and permission changes' } else { 'write' }
            foreach ($p in (Get-AdTargets $a)) {
                Assert-AdPathSafe $p
                $exists = Test-Path -LiteralPath $p
                if (-not $exists -and -not (AdGet $a 'createIfMissing' $false)) { Say 'SKIP' "$p not present"; continue }
                $isDir = (-not $exists) -or (Test-Path -LiteralPath $p -PathType Container)
                $inh = if ($isDir) { [int]([Security.AccessControl.InheritanceFlags]'ContainerInherit, ObjectInherit') } else { 0 }
                $pre = if ($exists) { Get-AdDenyRights $p $sid $inh } else { 0 }
                $added = $want -band (-bnot $pre)
                if (-not $added) { Say 'SKIP' "$p already denies $deny to $pr"; continue }
                # A folder created by -Apply is checked right after it is created (Invoke-AdItem).
                if ($prot -and $exists) { $why = Get-AdProtectRefusal $p $sid; if ($why) { throw $why } }
                $n = 0; if ($exists -and $isDir) { $n = @(Get-ChildItem -LiteralPath $p -Force -ErrorAction Stop).Count }
                $empty = [bool](AdGet $a 'emptyFirst' $false)
                $what = if ($empty -and $n) { "Empty ($n entries) and deny $deny" } else { "Deny $deny" }
                # after.rights is every right the tool has added for this key, so -Uninstall removes all of them even
                # when a rebuilt manifest added rights to an entry an earlier run made.
                $key = "acl:$p|$sid"; $all = $added
                if ($script:Ad.Journal.Contains($key)) { $all = $all -bor (Get-AdAclAdded $script:Ad.Journal[$key]) }
                $items.Add((New-AdItem $a 'acl' $key "$what to $pr on $p" @{ path = $p; sid = $sid; emptyFirst = $empty; inheritance = $inh; protect = $prot } `
                    @{ existed = $exists; entries = $n; preRights = $pre; addedRights = $added } ([ordered]@{ sid = $sid; rights = $all; inheritance = $inh })))
            }
        }
        'ifeo-block' {
            foreach ($n in @(AdGet $a 'target' @())) {
                $l = $n.ToLowerInvariant()
                if ($n -notmatch '^[\w\.\- ]+\.exe$') { throw "IFEO target must be a bare exe name: $n" }
                if ($script:AdGenericNames -contains $l) { throw "IFEO refuses generic name $n" }
                if ($script:Ad.CoreProcs -contains $l -or $script:Ad.Restartable -contains $l) { throw "core-function contract protects $n" }
                foreach ($sys in "$env:SystemRoot\System32", "$env:SystemRoot\SysWOW64") { if (Test-Path -LiteralPath (Join-Path $sys $n)) { throw "IFEO refuses ${n}: a Windows binary has that name" } }
                $sub = "SOFTWARE\Microsoft\Windows NT\CurrentVersion\Image File Execution Options\$n"
                $cur = Get-AdRegValue 'HKLM' 64 $sub 'Debugger'
                if ($cur.exists -and $cur.value -eq $script:Ad.IfeoTarget) { Say 'SKIP' "IFEO $n already blocked"; continue }
                if ($cur.exists) { Say 'WARN' "IFEO $n already has Debugger '$($cur.value)'; left alone"; continue }
                $items.Add((New-AdItem $a 'ifeo' "ifeo:$l" "Block $n from starting (IFEO Debugger)" @{ name = $n } @{ keyExisted = $cur.keyExisted } ([ordered]@{ debugger = $script:Ad.IfeoTarget })))
            }
        }
        'reg-set' {
            $hp = Split-AdRegPath (AdGet $a 'target'); $view = AdGet $a 'view' 64; $kind = AdGet $a 'kind' 'DWord'
            $vals = AdGet $a 'values'
            $pairs = @(); if ($vals) { foreach ($p in $vals.PSObject.Properties) { $pairs += , @($p.Name, $p.Value) } } else { $pairs += , @((AdGet $a 'name'), (AdGet $a 'value')) }
            foreach ($p in $pairs) {
                $v = if ($kind -eq 'Binary') { ConvertTo-AdHex $p[1] } else { $p[1] }
                $it = Get-AdRegSetItem $a $hp[0] $view $hp[1] $p[0] $v $kind "Set $($hp[0])\$($hp[1]) $($p[0]) = $(if ($kind -eq 'Binary') { "hex $v" } else { $v })"
                if ($it) { $items.Add($it) }
            }
        }
        'reg-delete-key' {
            foreach ($t in @(AdGet $a 'target' @())) {
                $hp = Split-AdRegPath $t; $view = AdGet $a 'view' 64; $match = AdGet $a 'match'; $md = AdGet $a 'matchDefault'
                if ($match -or $md) {
                    # match tests the subkey name, matchDefault its default value as stored (environment variables not
                    # expanded); with both, a subkey must pass both.
                    $hits = 0
                    foreach ($n in (Get-AdRegSubKeys $hp[0] $view $hp[1])) {
                        if ($match -and $n -notmatch $match) { continue }
                        if ($md -and "$((Get-AdRegValue $hp[0] $view "$($hp[1])\$n" '').value)" -notmatch $md) { continue }
                        $hits++; $it = Get-AdRegDelItem $a $hp[0] $view $hp[1] $n; if ($it) { $items.Add($it) }
                    }
                    if (-not $hits) { Say 'SKIP' "${t}: no subkey matches$(if ($match) { " name /$match/" })$(if ($match -and $md) { ' and' })$(if ($md) { " default value /$md/" }) (view $view)" }
                } else {
                    $i = $hp[1].LastIndexOf('\'); $it = Get-AdRegDelItem $a $hp[0] $view $hp[1].Substring(0, $i) $hp[1].Substring($i + 1)
                    if ($it) { $items.Add($it) } else { Say 'SKIP' "$t not present" }
                }
            }
        }
        'reg-delete-value' {
            # One item per value: names[] (exact, case-insensitive) or match (regex over the value names) in every key
            # target names (* and ? allowed per segment). Each value is checked by Get-AdRegValueRefusal first.
            $view = AdGet $a 'view' 64; $match = AdGet $a 'match'; $names = @(AdGet $a 'names' @())
            foreach ($t in @(AdGet $a 'target' @())) {
                $hp = Split-AdRegPath $t; $hits = 0
                $keys = @(Resolve-AdRegKeys $hp[0] $view $hp[1])
                foreach ($sub in $keys) {
                    $b = Open-AdHive $hp[0] $view; $k = $b.OpenSubKey($sub); $present = @(); if ($k) { $present = @($k.GetValueNames()); $k.Close() }; $b.Close()
                    $pick = if ($match) { @($present | Where-Object { $_ -and $_ -match $match }) } else { @($present | Where-Object { $_ -and $names -contains $_ }) }
                    foreach ($n in $pick) {
                        $cur = Get-AdRegValue $hp[0] $view $sub $n
                        if (-not $cur.exists) { continue }
                        $why = Get-AdRegValueRefusal $sub $n $cur
                        if ($why) { throw "refused value $($hp[0])\$sub $n`: $why" }
                        $hits++
                        $items.Add((New-AdItem $a 'regval' "regval:$($hp[0])$view\$sub|$n" "Delete registry value $($hp[0])\$sub $n (was $(Format-AdRegData $cur.kind $cur.value))" `
                            @{ hive = $hp[0]; view = "$view"; sub = $sub; name = $n } ([ordered]@{ exists = $true; kind = $cur.kind; value = $cur.value }) ([ordered]@{ exists = $false })))
                    }
                }
                if (-not $hits) {
                    $what = if ($match) { "value matching /$match/" } else { "value named $($names -join ', ')" }
                    Say 'SKIP' "${t}: no $what present ($(if ($keys.Count) { "$($keys.Count) key(s) searched" } else { 'key not present' }), view $view)"
                }
            }
        }
        'browser-ext-block' {
            # ExtensionInstallBlocklist is a key of numbered REG_SZ values ("1", "2", ...), each holding one id. The
            # browser takes the list from HKLM when HKLM has one, else from HKCU; the two are never merged, so a new
            # HKLM list would switch off the owner's HKCU list. Ids therefore go into the list in force: HKCU when only
            # HKCU has entries, else HKLM. An id that list already holds is a SKIP; otherwise it goes under the lowest
            # free number, so no entry of the owner's own policy is ever overwritten.
            $brs = @(@(AdGet $a 'browsers' @('chrome', 'edge')) | ForEach-Object { "$_".ToLowerInvariant() })
            $xs = @(AdGet $a 'ids' @())
            Say 'INFO' "$id`: while a policy value is set, $(($brs | ForEach-Object { $script:AdBrowsers[$_].Label }) -join ' and ') show$(if ($brs.Count -eq 1) { 's' }) 'Managed by your organization' (side effect of browser-ext-block)"
            foreach ($br in $brs) {
                $spec = $script:AdBrowsers[$br]; $lists = @{}
                foreach ($p in $spec.Policy, $spec.UserPolicy) {
                    $l = @{ Hive = $p[0]; View = $p[1]; Sub = "$($p[2])\ExtensionInstallBlocklist"; Held = @{}; Taken = @() }
                    $b = Open-AdHive $l.Hive $l.View; $k = $b.OpenSubKey($l.Sub)
                    if ($k) {
                        foreach ($n in $k.GetValueNames()) { $l.Taken += $n; $v = $k.GetValue($n); if ($v -is [string]) { $l.Held[$v.Trim().ToLowerInvariant()] = $n } }
                        $k.Close()
                    }
                    $b.Close(); $lists[$l.Hive] = $l
                }
                $use = if (-not $lists.HKLM.Taken.Count -and $lists.HKCU.Taken.Count) { $lists.HKCU } else { $lists.HKLM }
                $hive = $use.Hive; $view = $use.View; $sub = $use.Sub; $held = $use.Held; $taken = $use.Taken
                if ($hive -eq 'HKLM') {
                    $off = @($lists.HKCU.Held.Keys | Where-Object { -not $held.ContainsKey($_) } | Sort-Object)
                    if ($off.Count) { Say 'WARN' "$($spec.Label) ignores HKCU\$($lists.HKCU.Sub) while HKLM\$sub has entries (the lists are not merged), so these ids held only there are not blocked: $($off -join ', '); add them to the HKLM list" }
                }
                $missing = Get-AdRegMissingFrom $hive $view $sub
                foreach ($x in $xs) {
                    if ($held.ContainsKey($x)) { Say 'SKIP' "$($spec.Label) already blocks $x ($hive\$sub value $($held[$x]))"; continue }
                    $n = 1; while ($taken -contains "$n") { $n++ }
                    $taken += "$n"; $held[$x] = "$n"
                    $items.Add((New-AdItem $a 'extblock' "extblock:$hive$view\$sub|$x" "Block browser extension $x in $($spec.Label): $hive\$sub value $n" `
                        @{ hive = $hive; view = "$view"; sub = $sub; name = "$n"; id = $x; browser = $br } ([ordered]@{ exists = $false; created = $missing }) ([ordered]@{ name = "$n"; value = $x })))
                }
                if (AdGet $a 'removeExternal' $false) {
                    foreach ($loc in $spec.External) { foreach ($x in $xs) { $it = Get-AdRegDelItem $a $loc[0] $loc[1] "$($loc[2])" $x; if ($it) { $items.Add($it) } } }
                }
            }
        }
        'shellext-block' {
            $clsids = @(AdGet $a 'clsids' @()); $label = AdGet $a 'label' "$($script:Ad.Name) shell extension"
            foreach ($g in $clsids) {
                if ($g -notmatch '^\{[0-9A-Fa-f\-]{36}\}$') { throw "bad CLSID $g" }
                $it = Get-AdRegSetItem $a 'HKLM' 64 'SOFTWARE\Microsoft\Windows\CurrentVersion\Shell Extensions\Blocked' $g $label 'String' "Block shell extension $g (Shell Extensions\Blocked)"
                if ($it) { $items.Add($it) }
            }
            $parents = @('*', 'Directory', 'Directory\Background', 'Drive', 'Folder', 'AllFilesystemObjects', 'lnkfile') + @(AdGet $a 'handlerParents' @())
            $hm = AdGet $a 'handlerMatch'
            foreach ($h in 'HKLM', 'HKCU') {
                $classes = if ($h -eq 'HKLM') { 'SOFTWARE\Classes' } else { 'Software\Classes' }
                if (AdGet $a 'removeClsid' $true) {
                    foreach ($g in $clsids) { foreach ($c in 'CLSID', 'WOW6432Node\CLSID') { $it = Get-AdRegDelItem $a $h 64 "$classes\$c" $g; if ($it) { $items.Add($it) } } }
                }
                foreach ($p in $parents) {
                    $parent = "$classes\$p\shellex\ContextMenuHandlers"
                    $b = Open-AdHive $h 64; $k = $b.OpenSubKey($parent)
                    $names = @()
                    if ($k) {
                        foreach ($n in $k.GetSubKeyNames()) {
                            $sk = $k.OpenSubKey($n); $dv = if ($sk) { [string]$sk.GetValue('') } else { '' }; if ($sk) { $sk.Close() }
                            # A vendor's own "off" switch often appends '-' to the CLSID; that handler is still this one.
                            $dvN = $dv.Trim().TrimEnd('-'); $nN = $n.Trim().TrimEnd('-')
                            if (($hm -and $n -match $hm) -or ($clsids -contains $dvN) -or ($clsids -contains $nN)) { $names += $n }
                        }
                        $k.Close()
                    }
                    $b.Close()
                    foreach ($n in $names) { $it = Get-AdRegDelItem $a $h 64 $parent $n; if ($it) { $items.Add($it) } }
                }
            }
        }
        'toast-off' {
            $base = 'Software\Microsoft\Windows\CurrentVersion\Notifications\Settings'
            $existing = Get-AdRegSubKeys 'HKCU' 64 $base
            foreach ($t in @(AdGet $a 'target' @())) {
                $ids = if ($t -match '[\*\?]') { @($existing | Where-Object { $_ -like $t }) } else { @($t) }
                foreach ($i in $ids) { $it = Get-AdRegSetItem $a 'HKCU' 64 "$base\$i" 'Enabled' 0 'DWord' "Turn off Windows notifications for $i"; if ($it) { $items.Add($it) } }
            }
        }
        'firewall-block-program' {
            $dir = AdGet $a 'direction' 'Outbound'
            # A rule made for a program that is gone stays until -Uninstall; the SKIP line names it (never removed here).
            $left = "-Uninstall removes it, or drop the target and rebuild"
            $seen = @()
            foreach ($p in (Get-AdTargets $a)) {
                Assert-AdPathSafe $p -NoTouch
                $name = Get-AdFirewallRuleName $id $p; $seen += $name
                if (-not (Test-Path -LiteralPath $p -PathType Leaf)) {
                    Say 'SKIP' "$p not present$(if (@(Get-AdFirewallRules $name).Count) { "; rule $name still present; $left" })"; continue
                }
                $grp = "AppDebloat-$($script:Ad.AppId)"; $rules = @(Get-AdFirewallRules $name); $was = ''
                if ($rules.Count) {
                    # A rebuilt manifest may have changed the direction: the tool's own rule (its group) is replaced.
                    $other = @($rules | Where-Object { "$($_.Direction)" -ne $dir } | ForEach-Object { "$($_.Direction)" } | Select-Object -Unique)
                    if (-not $other.Count) { Say 'SKIP' "firewall rule exists: $name"; continue }
                    if (@($rules | Where-Object { "$($_.Group)" -ne $grp }).Count) { Say 'WARN' "firewall rule $name blocks $($other -join ', ') traffic, not $dir as the manifest asks, and is not in group $grp; left as is"; continue }
                    $was = " (replaces the rule that blocks $($other -join ', ') traffic)"
                }
                $items.Add((New-AdItem $a 'firewall' "fw:$name" "Firewall: block $dir traffic of $p$was" @{ name = $name; program = $p; direction = $dir; group = $grp; replace = [bool]$rules.Count } @{ ruleExisted = $false } `
                    ([ordered]@{ name = $name; program = $p; group = $grp; direction = $dir })))
            }
            # A glob target names nothing once its file is gone; the journal still knows the rules made for it.
            foreach ($e in @($script:Ad.Journal.Values)) {
                if ((AdGet $e 'actionId') -ne $id -or (AdGet $e 'prim') -ne 'firewall') { continue }
                $prog = [string](AdGet (AdGet $e 'data') 'program'); $name = [string](AdGet (AdGet $e 'data') 'name')
                if (-not $prog -or $seen -contains $name -or (Test-Path -LiteralPath $prog -PathType Leaf) -or -not (Test-AdTargetNames $a $prog)) { continue }
                if (@(Get-AdFirewallRules $name).Count) { Say 'SKIP' "$prog not present; rule $name still present; $left" }
            }
        }
        'hosts-block' {
            Say 'WARN' "$id`: hosts-block is discouraged (security products flag hosts edits); prefer firewall-block-program"
            if (-not (AdGet $a 'acknowledgeFlagging' $false)) { Say 'WARN' "$id`: skipped, set acknowledgeFlagging=true to use it"; break }
            $hosts = Join-Path $env:SystemRoot 'System32\drivers\etc\hosts'
            $text = if (Test-Path -LiteralPath $hosts) { [IO.File]::ReadAllText($hosts) } else { '' }
            $ms = 'microsoft\.com|windows\.com|windowsupdate|live\.com|msn\.com|bing\.com|office|azure|xbox|skype|msedge|msftncsi|msftconnecttest'
            $todo = @()
            foreach ($d in @(AdGet $a 'target' @())) {
                if ($d -notmatch '^[A-Za-z0-9\.\-]+$') { throw "bad domain $d" }
                if ($d -match $ms) { throw "hosts-block refuses Microsoft domain $d" }
                if ($text -notmatch ('(?m)^0\.0\.0\.0\s+' + [regex]::Escape($d) + '\s+# AppDebloat:' + [regex]::Escape($script:Ad.AppId))) { $todo += $d }
            }
            $lines = @($todo | ForEach-Object { "0.0.0.0 $_ # AppDebloat:$($script:Ad.AppId)" })
            if ($todo) { $items.Add((New-AdItem $a 'hosts' "hosts:$id" "hosts: sink $($todo -join ', ')" @{ domains = $todo; lines = $lines } @{} ([ordered]@{ lines = $lines }))) } else { Say 'SKIP' "$id`: hosts entries present" }
        }
        'preboot-file-edit' {
            $triples = @()
            $sec = AdGet $a 'section'; $set = AdGet $a 'set'
            if ($set) { foreach ($p in $set.PSObject.Properties) { $triples += , @($sec, $p.Name, [string]$p.Value) } }
            foreach ($ds in @(AdGet $a 'dropFromSections' @())) { if ($set) { foreach ($p in $set.PSObject.Properties) { $triples += , @($ds, $p.Name, $null) } } }
            $jobs = @(); $orig = @(); $diffs = @()
            foreach ($f in (Get-AdTargets $a)) {
                Assert-AdPathSafe $f -EditInPlace
                if (-not (Test-Path -LiteralPath $f -PathType Leaf)) { continue }
                $r = Update-AdIni $f $triples $false
                if ($r.Diff.Count) { $jobs += [ordered]@{ file = $f; triples = $triples }; $orig += [ordered]@{ file = $f; triples = $r.Original }; $diffs += $r.Diff }
            }
            if (-not $jobs) { Say 'SKIP' "$id`: settings already in place (or no file)"; break }
            $task = "$($script:Ad.Prefix)Debloat-Preboot-$id"
            $body = New-AdPrebootScript $task $jobs $false
            $scr = Join-Path $script:Ad.StateDir "preboot-$id.ps1"
            if ((Test-Path -LiteralPath $scr) -and ([IO.File]::ReadAllText($scr) -eq $body) -and @(Get-AdTasks '\' $task -Exact).Count) {
                Say 'SKIP' "$id`: edit already scheduled for next boot ($task)"; break
            }
            $items.Add((New-AdItem $a 'preboot' "preboot:$id" "Schedule pre-logon edit ($task): $((@($diffs) | Select-Object -Unique) -join ', ')" @{ task = $task; script = $scr; jobs = $jobs } @{ jobs = $orig } `
                ([ordered]@{ task = $task; identity = (Get-AdPrebootIdentity $scr); jobs = $jobs })))
        }
        'ini-set' {
            $sec = [string](AdGet $a 'section'); $key = [string](AdGet $a 'key'); $enc = [string](AdGet $a 'encoding' '')
            $val = AdGet $a 'value'; if ($null -ne $val) { $val = [string]::Format([Globalization.CultureInfo]::InvariantCulture, '{0}', $val) }
            $owners = Get-AdOwnerPaths $a
            foreach ($f in @(@(AdGet $a 'path') | ForEach-Object { Resolve-AdTargets $_ })) {
                Assert-AdPathSafe $f -EditInPlace
                if (-not (Test-Path -LiteralPath $f -PathType Leaf)) { Say 'SKIP' "$id`: $f not present"; continue }
                $r = Update-AdIni $f @(, @($sec, $key, $val)) $false $enc
                $was = $r.Original[0][2]
                $show = if ($null -eq $val) { "remove [$sec] $key" } else { "set [$sec] $key=$val" }
                if (-not $r.Diff.Count) { Say 'SKIP' "$id`: $f already has $(if ($null -eq $val) { "no [$sec] $key" } else { "[$sec] $key=$val" })"; continue }
                $run = @(Get-AdRunningByPath $owners)
                if ($run.Count) { Say 'WARN' "$id`: $f is not edited while $($run -join ', ') runs (onlyWhenNotRunning); deferred: close it and run again"; continue }
                $items.Add((New-AdItem $a 'iniset' "ini:$f|$sec|$key" "INI: $show in $f (was $(if ($null -eq $was) { 'absent' } else { "'$was'" }))" `
                    @{ path = $f; section = $sec; key = $key; value = $val; encoding = $enc; owners = $owners } `
                    ([ordered]@{ exists = ($null -ne $was); value = $was; sectionExisted = (@($r.Sections) -contains $sec) }) ([ordered]@{ exists = ($null -ne $val); value = $val })))
            }
        }
        'json-set' {
            $ptr = [string](AdGet $a 'pointer'); $segs = ConvertFrom-AdJsonPointer $ptr
            $want = ConvertTo-AdJsonCanon (AdGet $a 'value')
            $owners = Get-AdOwnerPaths $a
            foreach ($f in @(@(AdGet $a 'path') | ForEach-Object { Resolve-AdTargets $_ })) {
                Assert-AdPathSafe $f -EditInPlace
                if (-not (Test-Path -LiteralPath $f -PathType Leaf)) { Say 'SKIP' "$id`: $f not present"; continue }
                $doc = Read-AdTextFile $f
                try { $loc = [AppDebloat.JsonPtr]::Find($doc.Text, $segs) } catch { throw "$f is not JSON the engine can edit: $($_.Exception.GetBaseException().Message)" }
                if ($loc.Found) {
                    $raw = $doc.Text.Substring($loc.ValStart, $loc.ValEnd - $loc.ValStart)
                    if ([AppDebloat.JsonPtr]::Canon($raw) -eq $want) { Say 'SKIP' "$id`: $f already has $ptr = $want"; continue }
                    $orig = [ordered]@{ exists = $true; raw = $raw }; $after = [ordered]@{ exists = $true; canon = $want }
                    $was = $raw
                } elseif ($loc.ParentIsObject) {
                    $mem = New-AdJsonMember $segs $loc.Depth $want
                    $cptr = '/' + ((@($segs[0..$loc.Depth]) | ForEach-Object { $_.Replace('~', '~0').Replace('/', '~1') }) -join '/')
                    $orig = [ordered]@{ exists = $false; created = $cptr }; $after = [ordered]@{ exists = $true; canon = $want; created = $cptr; createdCanon = $mem.Value }
                    $was = 'absent'
                } else { throw "$f`: $ptr cannot be set, the part after '/$(($segs[0..([Math]::Max(0, $loc.Depth - 1))]) -join '/')' is not an object member (missing array element or scalar parent)" }
                $run = @(Get-AdRunningByPath $owners)
                if ($run.Count) { Say 'WARN' "$id`: $f is not edited while $($run -join ', ') runs (onlyWhenNotRunning); deferred: close it and run again"; continue }
                $items.Add((New-AdItem $a 'jsonset' "json:$f|$ptr" "JSON: set $ptr = $want in $f (was $was)" @{ path = $f; pointer = $ptr; canon = $want; owners = $owners } $orig $after))
            }
        }
        'hook' {
            $hn = AdGet $a 'hook'; $h = $script:Ad.Hooks[$hn]
            if (-not (AdGet $h 'Plan') -or -not (AdGet $h 'Apply')) { throw "hook '$hn' is not defined (needs Plan and Apply)" }
            foreach ($r in @(& $h.Plan $script:Ad $a)) {
                if ($null -eq $r) { continue }
                $items.Add((New-AdItem $a 'hook' "hook:$hn|$($r.Key)" $r.Desc @{ hook = $hn; data = $r.Data } $r.Original (AdGet $r 'After')))
            }
            if (-not $items.Count) { Say 'SKIP' "$id`: hook $hn reports nothing to change" }
        }
    }
    $items
}
function Get-AdSha256Text([string]$s) {
    $sha = [Security.Cryptography.SHA256]::Create()
    try { -join ($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($s)) | ForEach-Object { $_.ToString('x2') }) } finally { $sha.Dispose() }
}
function New-AdPrebootScript([string]$task, $jobs, [bool]$restore) {
    $json = (ConvertTo-Json -InputObject @($jobs) -Depth 6 -Compress) -replace "'", "''"
    $log = (Join-Path $script:Ad.StateDir 'preboot.log') -replace "'", "''"
    $tail = if ($restore) {
        # The state folder goes only after a clean -Uninstall (journal gone) and when no other restore is pending.
        "if (-not (Test-Path -LiteralPath '$($script:Ad.JournalPath -replace "'", "''")') -and -not (Get-ScheduledTask -TaskName '$($script:Ad.Prefix)Debloat-Restore-*' -ErrorAction SilentlyContinue)) { Remove-Item -LiteralPath '$($script:Ad.StateDir -replace "'", "''")' -Recurse -Force }"
    } else { '' }
    @"
`$ErrorActionPreference = 'Stop'
function Update-AdIni {${function:Update-AdIni}}
`$jobs = ConvertFrom-Json '$json'
`$ok = `$true
foreach (`$j in @(`$jobs)) {
    try { `$r = Update-AdIni `$j.file @(`$j.triples) `$true; Add-Content -LiteralPath '$log' "`$(Get-Date -Format s) $task `$(`$j.file) :: `$(`$r.Diff -join ', ')" }
    catch { `$ok = `$false; Add-Content -LiteralPath '$log' "`$(Get-Date -Format s) FAILED $task `$(`$j.file) :: `$(`$_.Exception.Message)" }
}
if (`$ok) {
    Unregister-ScheduledTask -TaskName '$task' -Confirm:`$false
    $tail
}
"@
}
function Register-AdPrebootTask([string]$task, [string]$scr, [string]$body) {
    Protect-AdStateDir
    [IO.File]::WriteAllText($scr, $body, (New-Object Text.UTF8Encoding $true))
    $act = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument "-NoProfile -ExecutionPolicy Bypass -File `"$scr`""
    $pri = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
    Register-ScheduledTask -TaskName $task -Action $act -Trigger (New-ScheduledTaskTrigger -AtStartup) -Principal $pri -Force `
        -Description "AppDebloat $($script:Ad.AppId): one-shot settings edit before logon, removes itself after success" | Out-Null
}

# ------------------------------------------------------------------ execution
function Get-AdBackupPath([string]$key) {
    $dir = Join-Path $script:Ad.StateDir 'backup'
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
    Join-Path $dir (Get-AdSha256Text $key).Substring(0, 16)
}
function Invoke-AdItem($it) {
    $d = $it.Data
    # Backups and exports happen before the journal line, so the journal always points at a real copy.
    $first = -not $script:Ad.JournalKeys.ContainsKey($it.Key)
    # Re-checked right before the change, before anything is journaled: a deferral leaves no trace.
    if ($it.Prim -eq 'dir2file' -and (Test-Path -LiteralPath $d.path -PathType Container)) {
        Assert-AdPathSafe $d.path
        foreach ($h in @($d.stopHosts)) { if ($h) { Stop-AdProcessByPath $h } }
        if ($d.checkLoaded) {
            $lu = Get-AdLoadedUnder $d.path -Fresh
            Write-AdModuleExemptions $lu
            if ($lu.Hits.Count -or $lu.Unknown.Count) {
                $why = if ($lu.Hits.Count) { "modules are loaded ($(@($lu.Hits | Select-Object -First 3) -join '; '))" } else { "$($lu.Unknown.Count) process(es) could not be inspected ($(@($lu.Unknown | Select-Object -First 3) -join '; '))" }
                Say 'WARN' "$($d.path) not replaced: $why; deferred: reboot and run again"; return 'warned'
            }
            # A choice to skip uninspectable processes is recorded next to the change it allowed.
            if ($lu.Ignored.Count) {
                Add-AdJournalLine ([ordered]@{ kind = 'note'; ts = (Get-Date -Format s); app = $script:Ad.AppId; actionId = $it.ActionId; key = $it.Key
                                               note = 'loaded-module check skipped uninspectable processes'; skipped = @($lu.Ignored)
                                               patterns = @(@($script:Ad.IgnoreUninspectable) | ForEach-Object { "$($_.Pattern) ($($_.Source))" }) })
            }
        }
    }
    if ($it.Prim -eq 'iniset' -or $it.Prim -eq 'jsonset') {
        $run = @(Get-AdRunningByPath @($d.owners))
        if ($run.Count) { Say 'WARN' "$($d.path) not edited while $($run -join ', ') runs (onlyWhenNotRunning); deferred: close it and run again"; return 'warned' }
    }
    if ($it.Prim -eq 'extblock' -and (Get-AdRegValue $d.hive $d.view $d.sub $d.name).exists) {
        Say 'WARN' "$($d.hive)\$($d.sub) value $($d.name) was taken after the plan was made; $($d.id) not written; deferred: run again"; return 'warned'
    }
    if ($first -and -not (Test-Path -LiteralPath $script:Ad.StateDir)) { Protect-AdStateDir }
    if ($first -and $it.Prim -eq 'regdel') {
        $dir = Join-Path $script:Ad.StateDir 'regkeys'; if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
        $file = Join-Path $dir ((Get-AdSha256Text $it.Key).Substring(0, 16) + '.reg')
        Invoke-AdNative reg.exe @('export', "$($d.hive)\$($d.parent)\$($d.name)", $file, '/y', "/reg:$($d.view)") | Out-Null
        $it.Original.export = $file
    }
    if ($first -and $it.Prim -eq 'file2dir' -and $d.backup -and (Test-Path -LiteralPath $d.path -PathType Leaf)) {
        $bk = (Get-AdBackupPath $it.Key) + '.bin'
        Copy-Item -LiteralPath $d.path -Destination $bk -Force
        if ((Get-AdSha256 $bk) -ne $it.Original.sha256) { throw "backup of $($d.path) does not match its hash; nothing changed" }
        $it.Original.backup = $bk
    }
    if ($first -and $it.Prim -eq 'dir2file' -and $d.backup -and (Test-Path -LiteralPath $d.path -PathType Container)) {
        $bk = (Get-AdBackupPath $it.Key) + '.dir'
        if (Test-Path -LiteralPath $bk) { Remove-Item -LiteralPath $bk -Recurse -Force }
        Copy-Item -LiteralPath $d.path -Destination $bk -Recurse -Force
        $n = @(Get-ChildItem -LiteralPath $bk -Recurse -File -Force).Count
        if ($n -ne $it.Original.fileCount) { throw "backup of $($d.path) holds $n of $($it.Original.fileCount) files; nothing changed" }
        $it.Original.backup = $bk
    }
    # Re-assert over a file the vendor wrote back: the first backup holds only the build found on first touch, so a
    # build that differs from it is kept as backup\<key16>.<sha8>.bin before it is replaced (an early sign of version
    # drift). The same build as the first original needs no copy.
    if (-not $first -and $it.Prim -eq 'file2dir' -and (Test-Path -LiteralPath $d.path -PathType Leaf)) {
        $je = if ($script:Ad.Journal.Contains([string]$it.Key)) { $script:Ad.Journal[[string]$it.Key] } else { $null }
        $was = [string](AdGet (AdGet $je 'original') 'sha256'); $now = Get-AdSha256 $d.path
        if ($now -ne $was -or -not $now) {
            $fv = $null; try { $fv = (Get-Item -LiteralPath $d.path -Force).VersionInfo.FileVersion } catch { }
            $s8 = if ($now) { $now.Substring(0, 8).ToLowerInvariant() } else { 'unreadable' }
            $kept = '; no copy kept (backup: false)'
            if (-not $now) { $kept = '; no copy kept (the file cannot be read)' }
            elseif ($d.backup) {
                $bk = "$(Get-AdBackupPath $it.Key).$s8.bin"
                if (-not ((Test-Path -LiteralPath $bk -PathType Leaf) -and (Get-AdSha256 $bk) -eq $now)) {
                    Copy-Item -LiteralPath $d.path -Destination $bk -Force
                    if ((Get-AdSha256 $bk) -ne $now) { throw "copy of the restored build $($d.path) does not match its hash; nothing changed" }
                }
                $kept = "; copy kept as $bk"
            }
            Say 'WARN' "$($d.path): vendor restored a different build (sha256 $s8, file version $(if ($fv) { $fv.Trim() } else { 'none' }))$kept"
        }
    }
    Write-AdJournal $it
    switch ($it.Prim) {
        'service' {
            # Neither failure is thrown: a security-suite veto of sc.exe is often a known failure (see New-AdFailure).
            $r = Invoke-AdNative sc.exe @('config', $d.name, 'start=', 'disabled') -NoThrow
            if ($r.Code) {
                $it | Add-Member -NotePropertyName FailedAt -NotePropertyValue (Get-Date) -Force   # for the event 7006 lookup
                return (New-AdFailure "sc.exe exit $($r.Code): $($r.Out)" $r.Code)
            }
            if ($d.stop -and $it.Original.state -eq 'Running') {
                $ev = $null; Stop-Service -Name $d.name -Force -ErrorAction SilentlyContinue -ErrorVariable ev
                if (@($ev).Count) { Say 'WARN' "service $($d.name) disabled but did not stop: $(@($ev)[0].Exception.Message)" }
            }
        }
        'task' { Disable-ScheduledTask -TaskPath $d.path -TaskName $d.name | Out-Null }
        'file2dir' {
            Assert-AdPathSafe $d.path
            foreach ($h in @($d.stopHosts)) { if ($h) { Stop-AdProcessByPath $h } }
            if ($d.path -like '*.exe') { Stop-AdProcessByPath $d.path }
            $lift = Enter-AdAclLift $d.path $it.ActionId $it.Key
            try { Set-AdPlaceholder $d.path 'Directory' } finally { Exit-AdAclLift $lift }
        }
        'dir2file' {
            $lift = Enter-AdAclLift $d.path $it.ActionId $it.Key
            try { Set-AdPlaceholder $d.path 'File' } finally { Exit-AdAclLift $lift }
        }
        'iniset' {
            Assert-AdPathSafe $d.path -EditInPlace
            [void](Update-AdIni $d.path @(, @($d.section, $d.key, $d.value)) $true ([string]$d.encoding))
        }
        'jsonset' {
            Assert-AdPathSafe $d.path -EditInPlace
            $doc = Read-AdTextFile $d.path; $segs = ConvertFrom-AdJsonPointer $d.pointer
            $loc = [AppDebloat.JsonPtr]::Find($doc.Text, $segs)
            if ($loc.Found) { $text = $doc.Text.Substring(0, $loc.ValStart) + $d.canon + $doc.Text.Substring($loc.ValEnd) }
            elseif ($loc.ParentIsObject) {
                $mem = New-AdJsonMember $segs $loc.Depth $d.canon
                $sep = if ([AppDebloat.JsonPtr]::IsEmptyObject($doc.Text, $loc.ParentOpen)) { '' } else { ',' }
                $text = $doc.Text.Substring(0, $loc.ParentOpen + 1) + $mem.Key + ':' + $mem.Value + $sep + $doc.Text.Substring($loc.ParentOpen + 1)
            } else { throw "$($d.pointer) cannot be set in $($d.path) (no object to add it to)" }
            Write-AdTextFile $d.path $text $doc
        }
        'acl' {
            Assert-AdPathSafe $d.path
            if (-not (Test-Path -LiteralPath $d.path)) { New-Item -ItemType Directory -Path $d.path -Force | Out-Null }
            if (AdGet $d 'protect' $false) { $why = Get-AdProtectRefusal $d.path $d.sid; if ($why) { throw $why } }
            $isDir = Test-Path -LiteralPath $d.path -PathType Container
            if ($d.emptyFirst -and $isDir) { Get-ChildItem -LiteralPath $d.path -Force | ForEach-Object { Remove-Item -LiteralPath $_.FullName -Recurse -Force -Confirm:$false } }
            Set-AdDenyAce $d.path $d.sid ([int]$it.Original.addedRights) ([int]$d.inheritance)
        }
        'ifeo' { Set-AdRegValue 'HKLM' 64 "SOFTWARE\Microsoft\Windows NT\CurrentVersion\Image File Execution Options\$($d.name)" 'Debugger' $script:Ad.IfeoTarget 'String' }
        'regset' { Set-AdRegValue $d.hive $d.view $d.sub $d.name $d.value $d.kind }
        'regdel' {
            $b = Open-AdHive $d.hive $d.view; $w = $null
            try { $w = $b.OpenSubKey($d.parent, $true) } catch { }
            $done = $false
            if ($w) { try { $w.DeleteSubKeyTree($d.name); $done = $true } catch { } finally { $w.Close() } }
            $b.Close()
            if (-not $done) {
                $r = Invoke-AdNative reg.exe @('delete', "$($d.hive)\$($d.parent)\$($d.name)", '/f', "/reg:$($d.view)") -NoThrow
                if ($r.Code) {
                    # A covered key goes the known-failure way (counted apart); any other key stays a counted WARN.
                    if ($it.Known) { return (New-AdFailure "cannot delete $($d.hive)\$($d.parent)\$($d.name): reg.exe exit $($r.Code): $($r.Out)" $r.Code) }
                    Say 'WARN' "Cannot delete $($d.hive)\$($d.parent)\$($d.name) (likely owned by TrustedInstaller); left in place"
                    Write-AdDenialDiagnostics $it
                    return 'warned'
                }
            }
        }
        { @('regval', 'extblock') -contains $_ } {
            # A failure is handed back, not thrown (see New-AdFailure), so a known failure leaves no TerminatingError.
            $err = $null; $b = Open-AdHive $d.hive $d.view; $k = $null
            try {
                if ($it.Prim -eq 'regval') { $k = $b.OpenSubKey($d.sub, $true); if ($k) { $k.DeleteValue($d.name, $false) } }
                else { Set-AdRegValue $d.hive $d.view $d.sub $d.name $d.id 'String' }
            } catch { $err = $_ } finally { if ($k) { $k.Close() }; $b.Close() }
            if ($err) {
                $what = if ($it.Prim -eq 'regval') { "delete $($d.hive)\$($d.sub) value $($d.name)" } else { "write $($d.hive)\$($d.sub) value $($d.name)" }
                return (New-AdFailure "cannot ${what}: $($err.Exception.GetBaseException().Message)" $(if (Test-AdAccessDenied $err) { 5 } else { 0 }))
            }
        }
        'firewall' {
            if (AdGet $d 'replace' $false) { foreach ($r in @(Get-AdFirewallRules $d.name)) { if ("$($r.Group)" -eq $d.group) { Remove-NetFirewallRule -Name $r.Name -ErrorAction Stop } } }
            New-NetFirewallRule -DisplayName $d.name -Group $d.group -Direction $d.direction -Action Block -Program $d.program | Out-Null
        }
        'hosts' {
            $hosts = Join-Path $env:SystemRoot 'System32\drivers\etc\hosts'
            [IO.File]::AppendAllText($hosts, "`r`n" + ($d.lines -join "`r`n") + "`r`n", [Text.Encoding]::ASCII)
        }
        'preboot' { Register-AdPrebootTask $d.task $d.script (New-AdPrebootScript $d.task $d.jobs $false) }
        'hook' { $h = $script:Ad.Hooks[$d.hook]; return (& $h.Apply $script:Ad $d.data $it) }
    }
}

# Undo one journal entry. Results: 'OK ...', 'SKIP ...' (already in its original state), 'GONE ...' (the object no
# longer exists), 'REINSTALL <path>', 'PENDING ...', 'WARN ...', 'CONFLICT ...'. The original is restored only when
# the current state still equals the state the tool wrote ('after'); anything else is a CONFLICT and is left alone.
function Invoke-AdUndo($e) {
    $d = $e.data; $o = $e.original; $af = AdGet $e 'after'
    if ($null -eq $af -and $e.prim -ne 'hook') { return "CONFLICT no after-state recorded (journal from an older engine): $($e.desc); check and restore it by hand" }
    switch ($e.prim) {
        'service' {
            $s = Get-AdService $d.name
            if (-not $s) { return "GONE service $($d.name) no longer exists" }
            $orig = "$(AdGet $o 'startMode')"
            if ("$($s.StartMode)" -ne 'Disabled') {
                if ("$($s.StartMode)" -eq $orig) { return "SKIP service $($d.name) is already $orig" }
                return "CONFLICT service $($d.name) start mode is now $($s.StartMode), not Disabled as the tool left it; left as is"
            }
            $m = @{ Auto = 'auto'; Manual = 'demand' }[$orig]
            if ($m -eq 'auto' -and (AdGet $o 'delayed' $false)) { $m = 'delayed-auto' }
            if (-not $m) { return "WARN service $($d.name): original start mode '$orig' is not restorable" }
            Invoke-AdNative sc.exe @('config', $d.name, 'start=', $m) | Out-Null
        }
        'task' {
            $t = @(Get-AdTasks $d.path $d.name -Exact) | Select-Object -First 1
            if (-not $t) { return "GONE task $($d.path)$($d.name) no longer exists" }
            if ((Get-AdTaskIdentity $t) -ne (AdGet $af 'actions')) { return "CONFLICT task $($d.path)$($d.name) now runs '$(Get-AdTaskIdentity $t)', not the action it had when disabled; left as is" }
            if ("$($t.State)" -ne 'Disabled') { return "SKIP task $($d.path)$($d.name) is enabled already" }
            if ((AdGet $o 'state') -ne 'Disabled') { Enable-ScheduledTask -TaskPath $d.path -TaskName $d.name | Out-Null }
        }
        'file2dir' {
            # The removal and the restore run with the tool's own deny entries above $p lifted (Enter-AdAclLift).
            $p = $d.path
            if (Test-Path -LiteralPath $p -PathType Leaf) { return "SKIP $p is a file again (restored by the vendor)" }
            $isPh = Test-Path -LiteralPath $p -PathType Container
            if ($isPh -and @(Get-ChildItem -LiteralPath $p -Force).Count) { return "CONFLICT placeholder folder $p is no longer empty; left as is" }
            $bk = AdGet $o 'backup'
            $restore = (AdGet $o 'existed') -and $bk -and (Test-Path -LiteralPath $bk -PathType Leaf) -and (Get-AdSha256 $bk) -eq (AdGet $o 'sha256')
            if ($isPh -or $restore) {
                $lift = Enter-AdAclLift $p (AdGet $e 'actionId') (AdGet $e 'key')
                try {
                    if ($isPh) { Remove-Item -LiteralPath $p -Force }
                    if ($restore) { Copy-Item -LiteralPath $bk -Destination $p }
                } finally { Exit-AdAclLift $lift }
            }
            if (-not (AdGet $o 'existed')) { return }
            if ($restore) { return "OK restored $p from backup" }
            return "REINSTALL $p"
        }
        'dir2file' {
            $p = $d.path
            if (Test-Path -LiteralPath $p -PathType Container) { return "SKIP $p is a folder again (restored by the vendor)" }
            $isPh = Test-Path -LiteralPath $p -PathType Leaf
            if ($isPh -and (Get-Item -LiteralPath $p -Force).Length -ne 0) { return "CONFLICT placeholder file $p now has content; left as is" }
            $bk = AdGet $o 'backup'
            $restore = (AdGet $o 'existed') -and $bk -and (Test-Path -LiteralPath $bk -PathType Container) -and @(Get-ChildItem -LiteralPath $bk -Recurse -File -Force).Count -eq (AdGet $o 'fileCount')
            if ($isPh -or $restore) {
                $lift = Enter-AdAclLift $p (AdGet $e 'actionId') (AdGet $e 'key')
                try {
                    if ($isPh) { $f = Get-Item -LiteralPath $p -Force; $f.IsReadOnly = $false; Remove-Item -LiteralPath $p -Force }
                    if ($restore) { Copy-Item -LiteralPath $bk -Destination $p -Recurse }
                } finally { Exit-AdAclLift $lift }
            }
            if (-not (AdGet $o 'existed')) { return }
            if ($restore) { return "OK restored $p from backup" }
            return "REINSTALL $p\"
        }
        'acl' {
            $p = $d.path
            if (-not (Test-Path -LiteralPath $p)) { return "GONE $p no longer exists" }
            $added = Get-AdAclAdded $e; $inh = [int](AdGet $d 'inheritance' 0)
            $have = (Get-AdDenyRights $p $d.sid $inh) -band $added
            if ($have -eq 0) { $r = "SKIP deny entry on $p already removed" }
            elseif ($have -ne $added) { return "CONFLICT deny entry for $($d.sid) on $p was changed since the tool added it; left as is" }
            else { Set-AdDenyAce $p $d.sid $added $inh -Remove; $r = $null }
            if (-not (AdGet $o 'existed') -and (Test-Path -LiteralPath $p -PathType Container) -and -not @(Get-ChildItem -LiteralPath $p -Force).Count) { Remove-Item -LiteralPath $p -Force }
            $out = @(); if ($r) { $out += $r }
            if ($d.emptyFirst -and (AdGet $o 'entries' 0)) { $out += "REINSTALL contents of $p" }
            return $out
        }
        'ifeo' {
            $ifeo = 'SOFTWARE\Microsoft\Windows NT\CurrentVersion\Image File Execution Options'
            $cur = Get-AdRegValue 'HKLM' 64 "$ifeo\$($d.name)" 'Debugger'
            if ($cur.exists -and $cur.value -ne (AdGet $af 'debugger')) { return "CONFLICT IFEO $($d.name) Debugger is now '$($cur.value)'; left as is" }
            $b = Open-AdHive 'HKLM' 64; $k = $b.OpenSubKey("$ifeo\$($d.name)", $true)
            if ($k) {
                if ($cur.exists) { $k.DeleteValue('Debugger') }
                $empty = ($k.ValueCount -eq 0 -and $k.SubKeyCount -eq 0); $k.Close()
                if ($empty -and -not (AdGet $o 'keyExisted')) { $pk = $b.OpenSubKey($ifeo, $true); $pk.DeleteSubKey($d.name); $pk.Close() }
            }
            $b.Close()
            if (-not $cur.exists) { return "SKIP IFEO $($d.name) Debugger already removed" }
        }
        'regset' {
            $cur = Get-AdRegValue $d.hive $d.view $d.sub $d.name
            $ov = AdGet $o 'value'; if ((AdGet $o 'kind') -eq 'Binary' -or (AdGet $o 'kind') -eq 'None') { $ov = ConvertTo-AdHex $ov }
            $isOrig = if (AdGet $o 'exists') { $cur.exists -and $cur.kind -eq (AdGet $o 'kind') -and (Test-AdSame $cur.value $ov) } else { -not $cur.exists }
            if ($isOrig) { return "SKIP $($d.hive)\$($d.sub) $($d.name) already has its original value" }
            if (-not ($cur.exists -and $cur.kind -eq (AdGet $af 'kind') -and (Test-AdSame $cur.value (AdGet $af 'value')))) {
                $now = if ($cur.exists) { Format-AdRegData $cur.kind $cur.value } else { 'absent' }
                return "CONFLICT $($d.hive)\$($d.sub) $($d.name) is now $now, not '$(@(AdGet $af 'value') -join ',')' as the tool wrote it; left as is"
            }
            if (AdGet $o 'exists') { Set-AdRegValue $d.hive $d.view $d.sub $d.name (AdGet $o 'value') (AdGet $o 'kind') }
            else {
                $b = Open-AdHive $d.hive $d.view; $k = $b.OpenSubKey($d.sub, $true)
                if ($k) { $k.DeleteValue($d.name); $empty = ($k.ValueCount -eq 0 -and $k.SubKeyCount -eq 0); $k.Close()
                          if ($empty -and -not (AdGet $o 'keyExisted')) { $b.DeleteSubKey($d.sub, $false) } }
                $b.Close()
            }
        }
        'regdel' {
            $key = "$($d.hive)\$($d.parent)\$($d.name)"
            if (Test-AdRegKey $d.hive $d.view "$($d.parent)\$($d.name)") { return "CONFLICT $key exists again; the saved export is not imported over it" }
            $f = AdGet $o 'export'
            if (-not $f -or -not (Test-Path -LiteralPath $f)) { return "WARN no export for $key" }
            Invoke-AdNative reg.exe @('import', $f, "/reg:$($d.view)") | Out-Null
        }
        'regval' {
            # The tool deleted the value: it comes back only while it is still absent and its key still exists.
            $key = "$($d.hive)\$($d.sub)"
            if (-not (Test-AdRegKey $d.hive $d.view $d.sub)) { return "GONE $key no longer exists; value $($d.name) not re-created" }
            $cur = Get-AdRegValue $d.hive $d.view $d.sub $d.name
            if ($cur.exists) {
                if ($cur.kind -eq (AdGet $o 'kind') -and (Test-AdSame $cur.value (AdGet $o 'value'))) { return "SKIP $key $($d.name) already has its original value" }
                return "CONFLICT $key $($d.name) now holds $(Format-AdRegData $cur.kind $cur.value), not absent as the tool left it, nor its original $(Format-AdRegData (AdGet $o 'kind') (AdGet $o 'value')); left as is"
            }
            Set-AdRegValue $d.hive $d.view $d.sub $d.name (AdGet $o 'value') (AdGet $o 'kind')
        }
        'extblock' {
            # Only the value the tool wrote goes, while it still holds the id; then the keys the tool created, while empty.
            $key = "$($d.hive)\$($d.sub)"; $n = [string](AdGet $af 'name'); $x = [string](AdGet $af 'value')
            $cur = Get-AdRegValue $d.hive $d.view $d.sub $n; $r = $null
            if (-not $cur.exists) { $r = "SKIP $key value $n ($x) already removed" }
            elseif (@('String', 'ExpandString') -notcontains $cur.kind -or "$($cur.value)".Trim() -ine $x) { return "CONFLICT $key value $n now holds $(Format-AdRegData $cur.kind $cur.value), not '$x' as the tool wrote it; left as is" }
            else { $b = Open-AdHive $d.hive $d.view; $k = $b.OpenSubKey($d.sub, $true); try { $k.DeleteValue($n) } finally { $k.Close(); $b.Close() } }
            $top = AdGet $o 'created'
            if ($top) { Remove-AdEmptyRegKeys $d.hive $d.view $d.sub ([string]$top) }
            return $r
        }
        'firewall' {
            $rules = @(Get-AdFirewallRules $d.name)
            if (-not $rules) { return "SKIP firewall rule $($d.name) already removed" }
            $res = @(); $adir = AdGet $af 'direction'   # older journals do not record it
            foreach ($r in $rules) {
                $prog = (Get-NetFirewallApplicationFilter -AssociatedNetFirewallRule $r -ErrorAction Stop).Program
                if ("$($r.Group)" -eq (AdGet $af 'group') -and $prog -ieq (AdGet $af 'program') -and (-not $adir -or "$($r.Direction)" -eq $adir)) { Remove-NetFirewallRule -Name $r.Name -ErrorAction Stop }
                else { $res += "CONFLICT firewall rule '$($d.name)' ($($r.Name)) now has group '$($r.Group)', program '$prog' and direction $($r.Direction); left as is" }
            }
            return $res
        }
        'hosts' {
            $hosts = Join-Path $env:SystemRoot 'System32\drivers\etc\hosts'
            if (-not (Test-Path -LiteralPath $hosts)) { return 'GONE hosts file is missing' }
            $enc = [Text.Encoding]::GetEncoding(28591)   # byte-preserving
            $text = $enc.GetString([IO.File]::ReadAllBytes($hosts))
            $nl = if ($text -match "`r`n") { "`r`n" } else { "`n" }
            $lines = New-Object System.Collections.Generic.List[string]; foreach ($l in [regex]::Split($text, '\r?\n')) { $lines.Add($l) }
            $removed = 0
            foreach ($w in @(AdGet $af 'lines' @())) { $i = $lines.IndexOf([string]$w); if ($i -ge 0) { $lines.RemoveAt($i); $removed++ } }
            if (-not $removed) { return 'SKIP hosts lines already removed' }
            [IO.File]::WriteAllBytes($hosts, $enc.GetBytes(($lines -join $nl)))
        }
        'preboot' {
            $t = @(Get-AdTasks '\' $d.task -Exact) | Select-Object -First 1
            if ($t) {
                if ((Get-AdTaskIdentity $t) -ne (AdGet $af 'identity')) { return "CONFLICT task $($d.task) now runs '$(Get-AdTaskIdentity $t)'; left as is" }
                Unregister-ScheduledTask -TaskName $d.task -Confirm:$false; return 'OK pending pre-logon edit cancelled'
            }
            # The edit ran. Restore only files whose values are still exactly what the tool wrote.
            $jobs = @(); $res = @()
            foreach ($oj in @(AdGet $o 'jobs' @())) {
                $wj = @(@($d.jobs) | Where-Object { $_.file -eq $oj.file }) | Select-Object -First 1
                if (-not (Test-Path -LiteralPath $oj.file -PathType Leaf)) { $res += "SKIP $($oj.file) no longer exists"; continue }
                if (-not $wj) { $res += "CONFLICT no written values recorded for $($oj.file)"; continue }
                $chk = Update-AdIni $oj.file @($wj.triples) $false
                if ($chk.Diff.Count) { $res += "CONFLICT $($oj.file) changed since the edit ($($chk.Diff -join ', ')); left as is"; continue }
                $jobs += $oj
            }
            if ($jobs) {
                $task = "$($script:Ad.Prefix)Debloat-Restore-$($e.actionId)"
                $scr = Join-Path $script:Ad.StateDir "restore-$($e.actionId).ps1"
                Register-AdPrebootTask $task $scr (New-AdPrebootScript $task $jobs $true)
                $script:Ad.KeepState = $true
                $res += "PENDING original settings are restored before the next logon ($task)"
            }
            return $res
        }
        'iniset' {
            $p = $d.path
            if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { return "GONE $p no longer exists" }
            $run = @(Get-AdRunningByPath @($d.owners))
            if ($run.Count) { return "WARN $p not restored while $($run -join ', ') runs (onlyWhenNotRunning); close it and run -Uninstall again" }
            $enc = [string]$d.encoding; $ov = AdGet $o 'value'; $av = AdGet $af 'value'
            $vsOrig = Update-AdIni $p @(, @($d.section, $d.key, $ov)) $false $enc
            if (-not $vsOrig.Diff.Count) { return "SKIP [$($d.section)] $($d.key) in $p already has its original value" }
            $vsAfter = Update-AdIni $p @(, @($d.section, $d.key, $av)) $false $enc
            if ($vsAfter.Diff.Count) {
                $now = $vsAfter.Original[0][2]; $nowT = if ($null -eq $now) { 'absent' } else { "'$now'" }
                return "CONFLICT [$($d.section)] $($d.key) in $p is now $nowT, not $(if ($null -eq $av) { 'absent' } else { "'$av'" }) as the tool wrote it; left as is"
            }
            $drop = if ((AdGet $o 'sectionExisted' $true) -or $null -ne $ov) { @() } else { @([string]$d.section) }
            [void](Update-AdIni $p @(, @($d.section, $d.key, $ov)) $true $enc $drop)
        }
        'jsonset' {
            $p = $d.path
            if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { return "GONE $p no longer exists" }
            $run = @(Get-AdRunningByPath @($d.owners))
            if ($run.Count) { return "WARN $p not restored while $($run -join ', ') runs (onlyWhenNotRunning); close it and run -Uninstall again" }
            $doc = Read-AdTextFile $p
            if (AdGet $o 'exists') {
                $loc = [AppDebloat.JsonPtr]::Find($doc.Text, (ConvertFrom-AdJsonPointer $d.pointer))
                if (-not $loc.Found) { return "CONFLICT $($d.pointer) in $p is gone, not '$(AdGet $af 'canon')' as the tool wrote it; left as is" }
                $cur = [AppDebloat.JsonPtr]::Canon($doc.Text.Substring($loc.ValStart, $loc.ValEnd - $loc.ValStart))
                if ($cur -eq [AppDebloat.JsonPtr]::Canon((AdGet $o 'raw'))) { return "SKIP $($d.pointer) in $p already has its original value" }
                if ($cur -ne (AdGet $af 'canon')) { return "CONFLICT $($d.pointer) in $p is now $cur, not $(AdGet $af 'canon') as the tool wrote it; left as is" }
                $text = $doc.Text.Substring(0, $loc.ValStart) + (AdGet $o 'raw') + $doc.Text.Substring($loc.ValEnd)
            } else {
                # The tool added the member at 'created' (with any missing parents); remove it only while it is unchanged.
                $loc = [AppDebloat.JsonPtr]::Find($doc.Text, (ConvertFrom-AdJsonPointer (AdGet $o 'created')))
                if (-not $loc.Found) { return "SKIP $(AdGet $o 'created') in $p is already absent" }
                $cur = [AppDebloat.JsonPtr]::Canon($doc.Text.Substring($loc.ValStart, $loc.ValEnd - $loc.ValStart))
                if ($cur -ne (AdGet $af 'createdCanon')) { return "CONFLICT $(AdGet $o 'created') in $p is now $cur, not $(AdGet $af 'createdCanon') as the tool added it; left as is" }
                $cut = [AppDebloat.JsonPtr]::MemberCut($doc.Text, $loc.MemberStart, $loc.ValEnd)
                $text = $doc.Text.Substring(0, $cut[0]) + $doc.Text.Substring($cut[1])
            }
            Write-AdTextFile $p $text $doc
        }
        'watchtask' {
            $t = @(Get-AdTasks '\' $d.name -Exact) | Select-Object -First 1
            if (-not $t) { return "GONE task $($d.name) no longer exists" }
            if ((Get-AdTaskIdentity $t) -ne (AdGet $af 'identity')) { return "CONFLICT task $($d.name) now runs '$(Get-AdTaskIdentity $t)', not what -Install registered; left as is" }
            Unregister-ScheduledTask -TaskName $d.name -Confirm:$false
        }
        'hook' {
            $h = $script:Ad.Hooks[$d.hook]
            # AdGet, not $h.Undo: the built script runs under Set-StrictMode 2, where a missing key throws.
            if (-not (AdGet $h 'Undo')) { return "WARN hook $($d.hook) has no Undo: $($e.desc)" }
            return (& $h.Undo $script:Ad $d.data $o $e)
        }
        default { return "WARN unknown journal entry type '$($e.prim)': $($e.desc)" }
    }
}

# ------------------------------------------------------------------ access-denied diagnostics
# True when an error record is an access denial (any language: HRESULT, Win32 code 5, exception type, category).
function Test-AdAccessDenied($er) {
    if ("$($er.CategoryInfo.Category)" -eq 'PermissionDenied') { return $true }
    $ex = $er.Exception
    while ($ex) {
        if ($ex -is [UnauthorizedAccessException] -or $ex -is [Security.SecurityException]) { return $true }
        if ($ex.HResult -eq -2147024891) { return $true }      # 0x80070005 E_ACCESSDENIED
        $nc = $ex.PSObject.Properties['NativeErrorCode']; if ($nc -and "$($nc.Value)" -eq 'AccessDenied') { return $true }
        if ($ex.Message -match '(?i)exit 5:|FAILED 5:|0x80070005|access (is )?denied|\u62D2\u7EDD\u8BBF\u95EE') { return $true }
        $ex = $ex.InnerException
    }
    $false
}
# System log event 7006 of the Service Control Manager within 5 s of $at, oldest first. 'ScRegSetValueExW call failed
# for Start' there means the denial hit the service's Start registry value, not the service's own permissions. The
# event names no service, so the match is by time only. Readable without elevation; never throws.
function Get-AdScmDenialEvents([datetime]$at) {
    $ev = $null; $found = @()
    try {
        $found = @(Get-WinEvent -FilterHashtable @{ LogName = 'System'; ProviderName = 'Service Control Manager'; Id = 7006
                                                    StartTime = $at.AddSeconds(-5); EndTime = $at.AddSeconds(5) } -ErrorAction SilentlyContinue -ErrorVariable ev)
    } catch { return "unavailable: $($_.Exception.Message)" }
    foreach ($x in @($ev)) { if ("$($x.FullyQualifiedErrorId)" -notlike 'NoMatchingEventsFound*') { return "unavailable: $($x.Exception.Message)" } }
    if (-not $found.Count) { return "none between $($at.AddSeconds(-5).ToString('HH:mm:ss')) and $($at.AddSeconds(5).ToString('HH:mm:ss'))" }
    foreach ($x in @($found | Sort-Object TimeCreated)) { "$($x.TimeCreated.ToString('HH:mm:ss.fff')) $(("$($x.Message)" -replace '\s+', ' ').Trim())" }
}
function Write-AdDiagLines([string]$label, [scriptblock]$get) {
    try { $out = @(& $get | ForEach-Object { "$_".TrimEnd() } | Where-Object { $_ }) } catch { $out = @("unavailable: $($_.Exception.Message)") }
    if (-not $out.Count) { $out = @('(nothing reported)') }
    Write-Host "  $label" -ForegroundColor Magenta
    foreach ($l in $out) { Write-Host "      $l" }
}
# Read-only facts about a denied change: who protects the object and what on the machine can veto it. The denial
# itself is never worked around (no ownership change, no ACL rewrite, no retry as another account).
function Write-AdDenialDiagnostics($it) {
    $d = $it.Data
    Write-Host "  ---- access denied on $($it.Prim) change: diagnostics (read-only) ----" -ForegroundColor Magenta
    switch ($it.Prim) {
        'service' {
            Write-AdDiagLines "service $($d.name) security descriptor (sc sdshow):" { Get-AdNativeLines sc.exe @('sdshow', $d.name) }
            Write-AdDiagLines "service $($d.name) protection level (sc qprotection):" { Get-AdNativeLines sc.exe @('qprotection', $d.name) }
            $at = AdGet $it 'FailedAt' (Get-Date)
            Write-AdDiagLines 'System log event 7006 (Service Control Manager) within 5 s of the failure (it names no service: matched by time only):' { Get-AdScmDenialEvents $at }
        }
        { @('regset', 'regdel', 'ifeo', 'regval', 'extblock') -contains $_ } {
            $sub = switch ($it.Prim) { 'regdel' { "$($d.parent)\$($d.name)" } 'ifeo' { "SOFTWARE\Microsoft\Windows NT\CurrentVersion\Image File Execution Options\$($d.name)" } default { $d.sub } }
            $hv = if ($it.Prim -eq 'ifeo') { 'HKLM' } else { $d.hive }; $vw = if ($it.Prim -eq 'ifeo') { 64 } else { $d.view }
            Write-AdDiagLines "registry key $hv\$sub owner and access:" {
                $b = Open-AdHive $hv $vw
                try {
                    $k = $b.OpenSubKey($sub, [Microsoft.Win32.RegistryKeyPermissionCheck]::Default, [Security.AccessControl.RegistryRights]::ReadPermissions)
                    if (-not $k) { 'key not present (the parent key decides)' }
                    else { try { $sd = $k.GetAccessControl(); "owner: $($sd.Owner)"; "sddl: $($sd.Sddl)" } finally { $k.Close() } }
                } finally { $b.Close() }
            }
        }
        { @('file2dir', 'dir2file', 'acl', 'iniset', 'jsonset') -contains $_ } {
            Write-AdDiagLines "file system object $($d.path):" {
                if (-not (Test-Path -LiteralPath $d.path)) { 'not present' }
                else { $acl = Get-Acl -LiteralPath $d.path; "owner: $($acl.Owner)"; "attributes: $((Get-Item -LiteralPath $d.path -Force).Attributes)"; "sddl: $($acl.Sddl)" }
            }
        }
        'task' { Write-AdDiagLines "scheduled task $($d.path)$($d.name):" { $t = @(Get-AdTasks $d.path $d.name -Exact) | Select-Object -First 1; if ($t) { "state: $($t.State)"; "author: $($t.Author)"; "principal: $($t.Principal.UserId) ($($t.Principal.RunLevel))" } else { 'not present' } } }
    }
    # Machine-wide facts, once per run.
    if (-not $script:Ad.Shown.ContainsKey('denial-machine')) {
        $script:Ad.Shown['denial-machine'] = 1
        if (Test-AdIsAdmin) { Write-AdDiagLines 'loaded file system minifilters (fltmc filters):' { Get-AdNativeLines fltmc.exe @('filters') } }
        else { Write-Host '  loaded file system minifilters: not listed (fltmc needs elevation)' -ForegroundColor Magenta }
        Write-AdDiagLines 'installed antivirus (SecurityCenter2):' {
            $ev = $null
            $av = @(Get-CimInstance -Namespace 'root/SecurityCenter2' -ClassName AntiVirusProduct -ErrorAction SilentlyContinue -ErrorVariable ev)
            if (@($ev).Count) { "unavailable: $(@($ev)[0].Exception.Message)" }
            foreach ($x in $av) { "$($x.displayName) (productState 0x$('{0:X6}' -f [int]$x.productState), $($x.pathToSignedProductExe))" }
        }
    } else { Write-Host '  (minifilters and antivirus: listed above)' -ForegroundColor Magenta }
    Write-Host '  A security suite can veto a change per item even when the permissions allow it. Do not work around it:' -ForegroundColor Magenta
    Write-Host '  record it in the manifest as knownFailure {reason, ref} (add targets to cover only this item) and use another' -ForegroundColor Magenta
    Write-Host '  lever (reference/levers.md).' -ForegroundColor Magenta
}

# ------------------------------------------------------------------ install / uninstall
function Register-AdWatchTask([string]$installed) {
    $user = [Security.Principal.WindowsIdentity]::GetCurrent().Name
    $act = New-ScheduledTaskAction -Execute 'conhost.exe' -Argument "--headless powershell.exe -NoProfile -ExecutionPolicy Bypass -File `"$installed`" -Auto"
    $logon = New-ScheduledTaskTrigger -AtLogOn -User $user
    $every = New-ScheduledTaskTrigger -Daily -At '00:00'
    $every.Repetition = (New-ScheduledTaskTrigger -Once -At '00:00' -RepetitionInterval (New-TimeSpan -Hours 6) -RepetitionDuration (New-TimeSpan -Days 1)).Repetition
    $pri = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Highest
    $set = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -ExecutionTimeLimit (New-TimeSpan -Minutes 15)
    Register-ScheduledTask -TaskName $script:Ad.WatchTask -Action $act -Trigger @($logon, $every) -Principal $pri -Settings $set -Force `
        -Description "AppDebloat $($script:Ad.AppId): re-confirms blocking actions at logon and every 6 hours" | Out-Null
}
# Files this tool writes into its state folder (elevated-tasks.json comes from scripts/elevated_readonly.ps1 -Key);
# anything else found there is left in place.
function Remove-AdStateFiles([switch]$KeepRestore) {
    $dir = $script:Ad.StateDir
    if (-not (Test-Path -LiteralPath $dir)) { return }
    $own = @('journal.jsonl', 'options.json', 'state.json', 'auto.log', 'history.log', 'regkeys', 'backup', 'elevated-tasks.json', "$($script:Ad.Prefix)Debloat.ps1")
    foreach ($f in @(Get-ChildItem -LiteralPath $dir -Force)) {
        $mine = ($own -contains $f.Name) -or ($f.Name -like 'preboot-*.ps1') -or ($f.Name -like '*.adtmp') -or
                (-not $KeepRestore -and ($f.Name -like 'restore-*.ps1' -or $f.Name -eq 'preboot.log'))
        if ($mine) { Remove-Item -LiteralPath $f.FullName -Recurse -Force }
    }
    if ($KeepRestore) { Say 'OK' 'State folder is removed by the restore task after the next boot'; return }
    if (@(Get-ChildItem -LiteralPath $dir -Force).Count) { Say 'INFO' "Left $dir in place: it holds files this tool did not write" }
    else { Remove-Item -LiteralPath $dir -Force; Say 'OK' "Removed $dir" }
}
# Returns the number of entries that were not cleanly undone (WARN, CONFLICT or failure).
function Invoke-AdUninstall {
    $journal = @(Read-AdJournal)
    # Placeholder undo lifts the tool's own deny entries above it (Enter-AdAclLift); one already undone here holds
    # none of its rights any more, so it is not lifted or put back.
    $script:Ad.Journal = [ordered]@{}; foreach ($e in $journal) { $script:Ad.Journal[[string]$e.key] = $e }
    $reinstall = @(); $issues = New-Object System.Collections.Generic.List[string]
    for ($i = $journal.Count - 1; $i -ge 0; $i--) {
        $e = $journal[$i]
        $close = [ordered]@{ kind = 'undone'; ts = (Get-Date -Format s); key = $e.key }
        if (-not (AdGet $e 'reversible' $true)) { Say 'INFO' "not reversible, left as is: $($e.desc)"; Add-AdJournalLine $close; continue }
        $bad = $null; $res = @()
        try { $res = @(Invoke-AdUndo $e) } catch {
            $bad = "FAIL $($_.Exception.Message)"; Say 'FAIL' "undo $($e.desc) :: $($_.Exception.Message)"
            if (Test-AdAccessDenied $_) { Write-AdDenialDiagnostics ([pscustomobject]@{ Prim = $e.prim; Data = $e.data; ActionId = $e.actionId }) }
        }
        foreach ($x in $res) {
            $s = "$x"; if (-not $s) { continue }
            if ($s -like 'REINSTALL *') { $reinstall += $s.Substring(10) }
            elseif ($s -like 'WARN *') { Say 'WARN' $s.Substring(5); $bad = $s }
            elseif ($s -like 'CONFLICT *') { Say 'CONFLICT' $s.Substring(9); $bad = $s }
            elseif ($s -like 'PENDING *') { Say 'OK' $s.Substring(8) }
            elseif ($s -like 'OK *') { Say 'OK' $s.Substring(3) }
            else { Say 'INFO' $s }
        }
        if ($bad) { $issues.Add("$($e.desc): $bad") }
        else { Add-AdJournalLine $close; Say 'OK' "undone: $($e.desc)" }
    }
    if ($issues.Count) {
        Write-Host ''
        Write-Host "Uninstall is NOT complete: $($issues.Count) item(s) were left as they are. The journal and $($script:Ad.StateDir) are kept." -ForegroundColor Red
        foreach ($x in $issues) { Write-Host "  - $x" }
        Write-Host 'Resolve each item by hand (restore the recorded value, or put back the state the tool wrote), then run -Uninstall again.'
        Write-Host 'Items already undone are recorded as such and are not replayed.'
    } else { Remove-AdStateFiles -KeepRestore:$script:Ad.KeepState }
    if ($reinstall) {
        Write-Host ''
        Write-Host "These vendor files were removed without a usable backup and come back only by reinstalling $($script:Ad.Name) over the top:"
        $reinstall | Select-Object -Unique | ForEach-Object { Write-Host "  $_" }
    }
    $issues.Count
}
function Write-AdHistory([string]$text) {
    if (-not (Test-Path -LiteralPath $script:Ad.StateDir)) { return }
    [IO.File]::AppendAllText((Join-Path $script:Ad.StateDir 'history.log'), ("{0} engine {1} {2} {3}`r`n" -f (Get-Date -Format s), $script:AdEngineVersion, $script:Ad.AppId, $text), (New-Object Text.UTF8Encoding $false))
}

# What one option gates: @{ Enables = 'id (evidence[: note])', ...; Skips = 'id (evidence)', ... }.
function Get-AdOptionGates($m, [string]$name) {
    $en = @(); $sk = @()
    foreach ($a in @(AdGet $m 'actions' @())) {
        $ev = AdGet $a 'evidence'; $note = AdGet $a 'evidenceNote' ''
        $txt = "$(AdGet $a 'id') ($ev$(if ($note -and $script:AdEvidenceActive -notcontains $ev) { ": $note" }))"
        if ((AdGet $a 'when') -eq $name) { $en += $txt }
        if ((AdGet $a 'unless') -eq $name) { $sk += $txt }
    }
    @{ Enables = $en; Skips = $sk }
}
# Every option that was not passed, with the action ids it would switch on or off and their evidence, so an
# option-gated action is never invisible in a plan.
# Options that gate no action (an option left behind when its actions were removed) are listed apart as unused.
function Write-AdOptionsNotSelected($m, [hashtable]$Options) {
    $off = @(); $unused = @()
    foreach ($o in @(AdGet $m 'options' @())) {
        $g = Get-AdOptionGates $m (AdGet $o 'name')
        if (-not ($g.Enables.Count + $g.Skips.Count)) { $unused += $o } elseif (-not $Options[(AdGet $o 'name')]) { $off += $o }
    }
    if ($off.Count) {
        Write-Host ''
        Write-Host ("Options Not Selected: {0} (pass the switch to select it)" -f $off.Count)
        foreach ($o in $off) {
            $g = Get-AdOptionGates $m (AdGet $o 'name')
            $parts = @()
            if ($g.Enables.Count) { $parts += "enables $($g.Enables -join ', ')" }
            if ($g.Skips.Count) { $parts += "skips $($g.Skips -join ', ')" }
            Write-Host ("  -{0}: {1}" -f (AdGet $o 'name'), ($parts -join '; ')) -ForegroundColor DarkCyan
            $h = AdGet $o 'help' ''; if ($h) { Write-Host "      $h" -ForegroundColor DarkGray }
        }
    }
    if ($unused.Count) {
        Write-Host ''
        Write-Host ("Unused Options: {0} (no action in this manifest uses them; passing them changes nothing)" -f $unused.Count)
        foreach ($o in $unused) { Write-Host ("  unused option -{0}{1}" -f (AdGet $o 'name'), $(if ($Options[(AdGet $o 'name')]) { ' (passed)' } else { '' })) -ForegroundColor DarkGray }
    }
}

# ------------------------------------------------------------------ entry point
# Mode: Plan | Apply | Install | Uninstall | Auto. Returns the process exit code:
# 0 ok, 1 at least one FAIL (or an Uninstall left items behind), 2 refused before any change (more than one mode,
# not elevated, invalid manifest, not installed, identity check failed, unsupported version).
function Invoke-AppDebloat {
    param([Parameter(Mandatory)][string]$ManifestJson, [hashtable]$Hooks = @{}, [string]$Mode = 'Plan',
          [hashtable]$Options = @{}, [string]$InstallRoot, [switch]$Force, [string]$ScriptPath, [string[]]$IgnoreUninspectable = @())
    if (@('Plan', 'Apply', 'Install', 'Uninstall', 'Auto') -notcontains $Mode) { Write-Host "[FAIL] unknown mode '$Mode'. Nothing was changed." -ForegroundColor Red; return 2 }
    $m = $ManifestJson | ConvertFrom-Json
    $script:Ad = @{ Changes = 0; Failures = 0; Warnings = 0; Conflicts = 0; WarnLines = (New-Object System.Collections.Generic.List[string])
                    FailLines = (New-Object System.Collections.Generic.List[string]); Hooks = $Hooks
                    Manifest = $m; Vars = @{}; Root = $null; Ver = $null; Uninstall = $null; KeepState = $false; Options = $Options
                    Bases = (New-Object System.Collections.Generic.List[string]); RealBases = @{}; CoreFiles = @(); PreserveFiles = @(); CoreProcs = @(); CoreSvcs = @(); Restartable = @()
                    JournalKeys = @{}; Journal = [ordered]@{}; Version = $null; AppId = 'unknown'; StateDir = $null; Mode = $Mode; ModMap = $null
                    Shown = @{}; IgnoreUninspectable = @(); KnownFailures = @{}; KnownTargets = @{}; KnownFailed = 0; KnownBy = [ordered]@{}
                    TaskCacheOn = $false; TaskCache = $null; SavedTasks = $null; IsAdmin = (Test-AdIsAdmin) }
    try { Test-AdManifest $m } catch { Say 'FAIL' $_.Exception.Message; return 2 }
    foreach ($x in @($IgnoreUninspectable | Where-Object { "$_".Trim() })) {
        $x = "$x".Trim() -replace '(?i)\.exe$', ''
        if ($x -notmatch '^[\w\.\-\*\? ]+$' -or $x -notmatch '[\w]') { Say 'FAIL' "-IgnoreUninspectable takes process names (wildcards allowed, not only wildcards): '$x'. Nothing was changed."; return 2 }
        $Ad.IgnoreUninspectable += [pscustomobject]@{ Pattern = $x; Source = '-IgnoreUninspectable' }
    }
    foreach ($x in @(AdGet $m 'checkLoadedExempt' @())) { $Ad.IgnoreUninspectable += [pscustomobject]@{ Pattern = ("$x".Trim() -replace '(?i)\.exe$', ''); Source = 'manifest checkLoadedExempt' } }
    foreach ($a in @(AdGet $m 'actions' @())) {
        $kf = AdGet $a 'knownFailure'; if (-not $kf) { continue }
        $Ad.KnownFailures[(AdGet $a 'id')] = $kf
        $ktp = $kf.PSObject.Properties['targets']
        if ($ktp) { $Ad.KnownTargets[(AdGet $a 'id')] = @(@($ktp.Value) | ForEach-Object { "$_" }) }   # tokens expanded below
    }
    $Ad.AppId = $m.id; $Ad.Name = $m.name; $Ad.Prefix = $m.taskPrefix
    $Ad.StateDir = Join-Path $env:ProgramData "AppDebloat\$($m.id)"
    $Ad.JournalPath = Join-Path $Ad.StateDir 'journal.jsonl'
    $Ad.WatchTask = "$($m.taskPrefix)Debloat-Watch"
    $Ad.IfeoTarget = Join-Path $env:SystemRoot "System32\AppDebloat-blocked\$($m.id).exe"   # never exists
    $Ad.OutOfProcessOnly = ((AdGet $m 'riskTier' 'normal') -eq 'out-of-process-only')
    $optFile = Join-Path $Ad.StateDir 'options.json'

    if ($Mode -ne 'Plan' -and -not (Test-AdIsAdmin)) { Say 'FAIL' "-$Mode needs an elevated (Administrator) PowerShell. Nothing was changed."; return 2 }
    $stopLog = { if ($Mode -eq 'Auto') { try { Stop-Transcript | Out-Null } catch { } } }
    if ($Mode -eq 'Auto') {
        if (Test-Path -LiteralPath $optFile) {
            $saved = [IO.File]::ReadAllText($optFile) | ConvertFrom-Json
            foreach ($p in $saved.PSObject.Properties) { $Options[$p.Name] = [bool]$p.Value }
        }
        if (Test-Path -LiteralPath $Ad.StateDir) { try { Start-Transcript -LiteralPath (Join-Path $Ad.StateDir 'auto.log') -Force | Out-Null } catch { } }
    }
    Initialize-AdForbidden
    try {
        $rr = Resolve-AdInstallRoot $m $InstallRoot; $Ad.Root = $rr[0]
        $Ad.RealRoot = Add-AdBase $Ad.Root 'install root'
        $Ad.Ver = Resolve-AdVersionDir $m $Ad.Root
        $pv = AdGet $m 'pathVars'; $pvp = if ($pv) { @($pv.PSObject.Properties) } else { @() }
        foreach ($p in $pvp) {
            $ev = AdGet $p.Value 'envVar'; $val = if ($ev -and [Environment]::GetEnvironmentVariable($ev)) { [Environment]::GetEnvironmentVariable($ev) } else { AdGet $p.Value 'default' }
            $Ad.Vars[$p.Name] = Get-AdNormal (Expand-AdPath $val)
        }
        foreach ($b in @(AdGet $m 'allowedRoots' @())) { [void](Add-AdBase (Get-AdNormal (Expand-AdPath $b)) "allowedRoots entry '$b'") }
        foreach ($k in @($Ad.KnownTargets.Keys)) {
            try { $Ad.KnownTargets[$k] = @($Ad.KnownTargets[$k] | ForEach-Object { ConvertTo-AdKnownName (Expand-AdPath $_) }) } catch { throw "knownFailure.targets of ${k}: $($_.Exception.Message)" }
        }
        $core = AdGet $m 'core'
        $Ad.CoreFiles = @(); foreach ($f in @(AdGet $core 'files' @())) { foreach ($x in (Resolve-AdTargets $f)) { $Ad.CoreFiles += (Get-AdNormal $x) } }
        $Ad.PreserveFiles = @(); foreach ($f in @(AdGet $core 'preserve' @())) { foreach ($x in (Resolve-AdTargets $f)) { $Ad.PreserveFiles += (Get-AdNormal $x) } }
        $Ad.CoreProcs = @(@(AdGet $core 'processes' @()) | ForEach-Object { $_.ToLowerInvariant() })
        $Ad.CoreSvcs = @(@(AdGet $core 'services' @()) | ForEach-Object { $_.ToLowerInvariant() })
        $Ad.Restartable = @(@(AdGet $core 'restartable' @()) | ForEach-Object { $_.ToLowerInvariant() })
    } catch {
        if ($Mode -eq 'Uninstall') { Say 'WARN' "$($_.Exception.Message) (continuing: the journal alone drives -Uninstall)" }
        else {
            Say 'FAIL' $_.Exception.Message
            if ($Mode -eq 'Auto') { Write-AdHistory "REFUSED: nothing changed. WARN: $($_.Exception.Message)" }
            & $stopLog; return 2
        }
    }
    if ($Mode -eq 'Uninstall') {
        Write-Host "$($m.name) debloat: UNINSTALL (journal replay in reverse)"
        $left = Invoke-AdUninstall
        if ($left -or $Ad.Failures) { return 1 }
        return 0
    }

    $Ad.Version = Get-AdVersion $m
    $supported = Test-AdVersionSupported $Ad.Version $m
    $fingerprint = "$($Ad.Version)|$(Split-Path -Leaf $Ad.Ver)"
    $statePath = Join-Path $Ad.StateDir 'state.json'
    $prevFp = $null; if (Test-Path -LiteralPath $statePath) { $prevFp = AdGet ([IO.File]::ReadAllText($statePath) | ConvertFrom-Json) 'fingerprint' }
    $sup = AdGet (AdGet $m 'version') 'supported'
    $supText = (@(AdGet $sup 'versions' @()) -join ', ') + $(if (AdGet $sup 'allowRange' $false) { " or $(AdGet $sup 'min')..$(AdGet $sup 'max')" } else { '' })

    Write-Host ("App           : {0} ({1})" -f $m.name, $m.id)
    Write-Host ("Install root  : {0}" -f $Ad.Root)
    Write-Host ("Found by      : {0}" -f $rr[1])
    Write-Host ("Identity      : passed ({0})" -f $rr[2])
    if ($Ad.RealRoot -ine $Ad.Root) { Write-Host "Real path     : $($Ad.RealRoot)" }
    if ($Ad.Ver -ne $Ad.Root) { Write-Host "Version dir   : $($Ad.Ver)" }
    Write-Host ("Version       : {0}{1}" -f $(if ($Ad.Version) { $Ad.Version } else { 'unknown' }), $(if ($supported) { '' } else { "  (NOT SUPPORTED; supported: $supText)" }))
    Write-Host ("Mode          : {0}" -f $(if ($Mode -eq 'Plan') { 'dry run (add -Apply to change things)' } elseif ($Mode -eq 'Auto') { 'AUTO (blocking actions only)' } else { $Mode.ToUpper() }))
    $on = @($Options.Keys | Where-Object { $Options[$_] }); if ($on) { Write-Host "Options       : $($on -join ', ')" }
    if (@($Ad.IgnoreUninspectable).Count) { Write-Host "Module check  : skips these processes when they cannot be inspected: $((@($Ad.IgnoreUninspectable) | ForEach-Object { "$($_.Pattern) ($($_.Source))" }) -join ', '); journaled with each change it allows" }
    if (-not $Ad.Version) { Say 'WARN' 'No version.sources entry returned a version, so -Apply/-Install/-Auto will refuse. Check the manifest sources against the installed files before going further.' }
    Write-Host ''
    if (-not $supported) {
        $vt = if ($Ad.Version) { "version $($Ad.Version)" } else { 'the version could not be read; it' }
        $msg = "$vt is not one this manifest was built from (supported: $supText)"
        if ($Mode -eq 'Plan') { Say 'WARN' "$msg; the plan below may be stale" }
        elseif ($Force) { Say 'WARN' "$msg; continuing because -Force was given" }
        elseif ($Mode -eq 'Auto') {
            Say 'WARN' "$msg. Nothing was changed; re-run inventory (P1 to P3) and rebuild, or run once with -Apply -Force"
            Write-AdHistory "$fingerprint REFUSED: 0 change(s). WARN: $msg"
            & $stopLog; return 2
        } else {
            Say 'FAIL' "$msg. Nothing was changed: re-run inventory (P1 to P3) and add it to version.supported.versions, or pass -Force"
            return 2
        }
    }
    if ($Mode -eq 'Auto' -and $prevFp -and $prevFp -ne $fingerprint) { Say 'WARN' "version fingerprint changed $prevFp -> ${fingerprint}: only blocking actions are re-applied; re-run inventory (P1 to P3)" }

    # Active journal entries by key: the plan re-creates placeholders and names leftover firewall rules from them, and
    # placeholder changes lift the tool's own deny entries found there. Write-AdJournal keeps it current.
    $Ad.JournalKeys = @{}; $Ad.Journal = [ordered]@{}
    foreach ($e in @(Read-AdJournal)) { $k = [string]$e.key; $Ad.Journal[$k] = $e; $Ad.JournalKeys[$k] = Get-AdAfterKey (AdGet $e 'after') }
    $wkey = "watchtask:$($Ad.WatchTask)"
    if ($Mode -eq 'Install') {
        # Checked before anything changes; the task itself is registered only after a clean apply (see below).
        if (-not $ScriptPath) { Say 'FAIL' '-Install needs the script path'; return 2 }
        if (@(Get-AdTasks '\' $Ad.WatchTask -Exact).Count -and -not $Ad.JournalKeys.ContainsKey($wkey)) {
            Say 'FAIL' "a scheduled task named $($Ad.WatchTask) exists that this tool did not register; not replacing it. Nothing was changed."; return 2
        }
    }

    # Plan: every active action is resolved to concrete items first; the same list is printed and then executed.
    # An action backed only by inferred or hypothesis evidence is inactive unless its 'when' option is given.
    $items = New-Object System.Collections.Generic.List[object]
    $inactive = New-Object System.Collections.Generic.List[string]
    $known = New-Object System.Collections.Generic.List[object]; $planFailed = @{}; $planWarned = @{}
    $Ad.TaskCacheOn = $true; $Ad.TaskCache = $null
    foreach ($a in @(AdGet $m 'actions' @())) {
        $w = AdGet $a 'when'; $u = AdGet $a 'unless'; $ev = AdGet $a 'evidence'
        if ($Mode -eq 'Auto' -and -not (AdGet $a 'reapply' $false)) { continue }
        if ($script:AdEvidenceActive -notcontains $ev -and -not $Options[$w]) {
            $note = AdGet $a 'evidenceNote' ''
            $inactive.Add(("[{0}] {1}, {2}: evidence is {3}{4}. Enable with -{5}" -f (AdGet $a 'id'), (AdGet $a 'type'), (AdGet $a 'category'), $ev, $(if ($note) { " ($note)" } else { '' }), $w))
            continue
        }
        if ($w -and -not $Options[$w]) { continue }
        if ($u -and $Options[$u]) { continue }
        $aid = AdGet $a 'id'; $kf = $Ad.KnownFailures[$aid]; if ($kf) { $known.Add($a) }
        # A plan that deferred a target with a WARN (loaded modules, a foreign IFEO Debugger) may yield no item while
        # the knownFailure still applies; $planWarned keeps its WARN header below.
        $w0 = $Ad.Warnings
        try { foreach ($it in (Get-AdActionPlan $a)) { $it.Known = Get-AdKnownFailure $it; $items.Add($it) } }
        catch {
            $planFailed[$aid] = 1
            # A failure before any item exists is known only under the whole-action form: targets cannot name it.
            if ($kf -and -not $Ad.KnownTargets.ContainsKey($aid)) {
                Add-AdKnownFailed $aid $kf
                Say 'WARN' "[$aid] known failure (ref $(AdGet $kf 'ref')): $(AdGet $kf 'reason') :: $($_.Exception.Message)" -NoCount
            }
            else { Say 'FAIL' "${aid}: $($_.Exception.Message)" }
        }
        if ($Ad.Warnings -gt $w0) { $planWarned[$aid] = 1 }
    }
    $Ad.TaskCacheOn = $false; $Ad.TaskCache = $null
    $knownItems = @($items | Where-Object { $_.Known }).Count
    $knownText = if ($knownItems) { ", $knownItems of them known to fail" } else { '' }
    Write-Host ''
    Write-Host ("Plan: {0} change(s){1}" -f $items.Count, $knownText)
    $n = 0
    foreach ($it in $items) {
        $n++
        Write-Host ('  {0,3}. [{1}] {2}' -f $n, $it.ActionId, $it.Desc) -ForegroundColor Yellow
        Write-Host ('       {0}, {1}, evidence {2}{3}{4}' -f $it.ActionType, $it.Category, $it.Evidence, $(if ($it.Reapply) { ', reapply' } else { '' }),
            $(if ($it.Known) { ", known to fail (ref $(AdGet $it.Known 'ref'))" } else { '' })) -ForegroundColor DarkGray
    }
    if ($inactive.Count) {
        Write-Host ''
        Write-Host ("Inactive: {0} action(s) not backed by observed or anchored evidence (they run only with their option)" -f $inactive.Count)
        foreach ($x in $inactive) { Say 'INACTIVE' $x }
    }
    if ($Mode -ne 'Auto') { Write-AdOptionsNotSelected $m $Options }
    # A recorded, explained failure is named on every run, so it is neither forgotten nor mistaken for a new one. One
    # that covers no planned item and saw no plan-time failure or WARN (its targets are gone, as after a vendor removed
    # an old updater) is an INFO that says to drop it instead; not for task-disable without elevation, which cannot see
    # SYSTEM tasks, and not when the plan deferred a target with a WARN.
    if ($known.Count) {
        Write-Host ''
        Write-Host ("Known Failures: {0} action(s) carry a recorded failure (logged as WARN, counted apart from failures and warnings)" -f $known.Count)
        foreach ($a in $known) {
            $aid = AdGet $a 'id'; $kf = $Ad.KnownFailures[$aid]
            $blind = ((AdGet $a 'type') -eq 'task-disable' -and -not $Ad.IsAdmin)
            if (-not $blind -and -not $planFailed.ContainsKey($aid) -and -not $planWarned.ContainsKey($aid) -and -not @($items | Where-Object { $_.ActionId -eq $aid -and $_.Known }).Count) {
                Say 'INFO' "knownFailure $(AdGet $kf 'ref') on $aid covered nothing this run (targets not present or already in place); remove it from the manifest"
                continue
            }
            $for = if ($Ad.KnownTargets.ContainsKey($aid)) { " for $(@(AdGet $kf 'targets') -join ', ')" } else { '' }
            Say 'WARN' "[$aid] knownFailure$for (ref $(AdGet $kf 'ref')): $(AdGet $kf 'reason')" -NoCount
        }
    }
    Write-Host ''
    $apply = ($Mode -ne 'Plan')
    if ($apply -and $items.Count) {
        foreach ($it in $items) {
            # A step reports failure by throwing or by returning New-AdFailure; both end in Write-AdItemFailure.
            $er = $null
            try {
                $r = Invoke-AdItem $it
                $er = Get-AdFailure $r
                if (-not $er) {
                    if (@($r) -contains 'warned') { continue }      # WARN-only steps are not changes
                    $Ad.Changes++; Say 'OK' $it.Desc
                    if ($it.Known) { Say 'INFO' "[$($it.ActionId)] knownFailure (ref $(AdGet $it.Known 'ref')) covers this item but it succeeded; remove it from the manifest once it stays fixed" }
                }
            } catch { $er = $_ }
            if ($er) { Write-AdItemFailure $it $er }
        }
    }
    if ($Mode -eq 'Install') {
        # The watch task re-applies this plan every 6 hours, so it is registered only after an apply without
        # failures; failures recorded as knownFailure do not count.
        Write-Host ''
        if ($Ad.Failures) {
            Write-Host "Watch task NOT registered: the apply above had $($Ad.Failures) failure(s). Fix them, or record a failure that is understood and cannot be fixed as knownFailure {reason, ref} on its action, rebuild the script and run -Install again." -ForegroundColor Red
        } else {
            Protect-AdStateDir
            $installed = Join-Path $Ad.StateDir "$($m.taskPrefix)Debloat.ps1"
            if ($ScriptPath -ne $installed) { Copy-Item -LiteralPath $ScriptPath -Destination $installed -Force }
            $opt = [ordered]@{}; foreach ($o in @(AdGet $m 'options' @())) { $opt[$o.name] = [bool]$Options[$o.name] }
            [IO.File]::WriteAllText($optFile, ($opt | ConvertTo-Json), (New-Object Text.UTF8Encoding $false))
            $wi = [pscustomobject]@{ ActionId = 'install'; ActionType = 'watch-task'; Prim = 'watchtask'; Key = $wkey; Desc = "Scheduled task $($Ad.WatchTask)"
                                     Reversible = $true; Evidence = 'observed'; Data = @{ name = $Ad.WatchTask }; Original = @{ existed = $false }
                                     After = [ordered]@{ identity = (Get-AdWatchIdentity $installed) } }
            try {
                Write-AdJournal $wi
                Register-AdWatchTask $installed
                Say 'OK' "Installed to $installed and registered task $($Ad.WatchTask) (logon + every 6 h)$(if ($Ad.KnownFailed) { "; $($Ad.KnownFailed) known failure(s) stay as WARN" })"
            } catch { Say 'FAIL' "registering $($Ad.WatchTask) :: $($_.Exception.Message)" }
        }
    }
    if ($apply -and (Test-Path -LiteralPath $Ad.StateDir)) {
        [IO.File]::WriteAllText($statePath, ([ordered]@{ fingerprint = $fingerprint; lastRun = (Get-Date -Format s); engine = $script:AdEngineVersion } | ConvertTo-Json), (New-Object Text.UTF8Encoding $false))
    }
    if ($Mode -eq 'Auto') {
        # One compact line: known failures by action id and count (their full text is in auto.log), then the FAIL
        # text (desc :: message, unique, each cut to 200 characters), then other WARNs.
        $kb = if ($Ad.KnownBy.Count) { ' [' + ((@($Ad.KnownBy.Keys) | ForEach-Object { "$_ x$($Ad.KnownBy[$_].N), ref $($Ad.KnownBy[$_].Ref)" }) -join '; ') + ']' } else { '' }
        $fl = @($Ad.FailLines | ForEach-Object { $s = ("$_" -replace '\s+', ' ').Trim(); if ($s.Length -gt 200) { $s.Substring(0, 197) + '...' } else { $s } } | Select-Object -Unique)
        $fail = if ($fl.Count) { ' FAIL: ' + ($fl -join ' | ') } else { '' }
        $warn = if ($Ad.WarnLines.Count) { ' WARN: ' + (($Ad.WarnLines | Select-Object -Unique) -join ' | ') } else { '' }
        Write-AdHistory ("{0}: {1} change(s), {2} failure(s), {3} known failure(s){4}{5}{6}" -f $fingerprint, $Ad.Changes, $Ad.Failures, $Ad.KnownFailed, $kb, $fail, $warn)
        & $stopLog
    }
    if (-not $apply) { Write-Host "$($items.Count) change(s) planned$knownText. Run again with -Apply in an elevated PowerShell to execute exactly this plan." }
    else {
        Write-Host "$($Ad.Changes) change(s) made, $($Ad.Warnings) warning(s), $($Ad.Failures) failure(s), $($Ad.KnownFailed) known failure(s)."
        if (@($items | Where-Object { $_.Prim -eq 'preboot' })) { Write-Host 'Reboot: a pre-logon settings edit is scheduled.' }
    }
    if ($Ad.Failures) { return 1 }
    0
}

# ------------------------------------------------------------------ build step
# Inlines this engine, the manifest and optional hooks into the template: one self-contained per-app script.
function New-AppScript {
    param([Parameter(Mandatory)][string]$ManifestPath, [string]$HooksPath, [Parameter(Mandatory)][string]$OutFile,
          [string]$TemplatePath, [string]$EnginePath = $script:AdEngineSource)
    if (-not $EnginePath -or (Split-Path -Leaf $EnginePath) -ne 'DebloatEngine.ps1') { throw 'pass -EnginePath (path to DebloatEngine.ps1)' }
    if (-not $TemplatePath) { $TemplatePath = Join-Path (Split-Path (Split-Path $EnginePath -Parent) -Parent) 'templates\app-debloat.template.ps1' }
    $json = [IO.File]::ReadAllText($ManifestPath).Trim()
    $m = $json | ConvertFrom-Json
    Test-AdManifest $m
    if ($json -match "(?m)^'@") { throw "manifest JSON must not contain a line starting with '@" }
    $hooks = if ($HooksPath) { [IO.File]::ReadAllText($HooksPath).Trim() } else { '# (no app-specific hooks)' }
    $engine = ([IO.File]::ReadAllText($EnginePath) -replace '(?m)^#Requires.*\r?\n', '').Trim()
    $optParams = @(); $optHelp = @()
    foreach ($o in @(AdGet $m 'options' @())) {
        $optParams += "    [switch]`$$($o.name),"
        $g = Get-AdOptionGates $m $o.name
        if (-not ($g.Enables.Count + $g.Skips.Count)) { Write-Host "[WARN] option -$($o.name) gates no action in this manifest (no 'when' or 'unless' names it); the script lists it as an unused option" -ForegroundColor Magenta }
        $h = AdGet $o 'help' ''
        if ($g.Enables.Count) { $h += " Enables: $($g.Enables -join ', ')." }
        if ($g.Skips.Count) { $h += " Skips: $($g.Skips -join ', ')." }
        $optHelp += ".PARAMETER $($o.name)", "  $h"
    }
    $t = [IO.File]::ReadAllText($TemplatePath)
    $t = $t.Replace('@@APP_NAME@@', $m.name).Replace('@@APP_PREFIX@@', $m.taskPrefix).Replace('@@APP_ID@@', $m.id)
    $t = $t.Replace('    #@@OPTION_PARAMS@@', ($optParams -join "`r`n"))
    $t = $t.Replace('#@@OPTION_HELP@@', ($optHelp -join "`r`n"))
    $t = $t.Replace('#@@MANIFEST@@', $json)
    $t = $t.Replace('#@@HOOKS@@', $hooks)
    $t = $t.Replace('#@@ENGINE@@', "# ---- inlined DebloatEngine.ps1 $($script:AdEngineVersion) ----`r`n$engine`r`n# ---- end of engine ----")
    $t = $t -replace "(?<!`r)`n", "`r`n"
    [IO.File]::WriteAllText($OutFile, $t, (New-Object Text.UTF8Encoding $true))
    $errs = $null; [void][Management.Automation.Language.Parser]::ParseFile($OutFile, [ref]$null, [ref]$errs)
    if ($errs) { throw "built script does not parse: $($errs[0].Message) (line $($errs[0].Extent.StartLineNumber))" }
    $OutFile
}
# ---- end of engine ----

if (-not (Get-Command Invoke-AppDebloat -ErrorAction SilentlyContinue)) {
    throw 'This is the unbuilt template. Build a per-app script with New-AppScript (scripts/DebloatEngine.ps1).'
}
$mode = Resolve-AdMode -Apply:$Apply -Install:$Install -Uninstall:$Uninstall -Auto:$Auto
if (-not $mode) { exit 2 }
$opts = @{}
$optProp = ($ManifestJson | ConvertFrom-Json).PSObject.Properties['options']
if ($optProp) { foreach ($o in @($optProp.Value)) { $opts[$o.name] = [bool](Get-Variable -Name $o.name -ValueOnly) } }
$code = @(Invoke-AppDebloat -ManifestJson $ManifestJson -Hooks $Hooks -Mode $mode -Options $opts `
    -InstallRoot $InstallRoot -Force:$Force -ScriptPath $PSCommandPath -IgnoreUninspectable $IgnoreUninspectable)[-1]
exit $code
